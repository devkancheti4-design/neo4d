"""The 32-kind router's numbers, exact - for prompts/ROUTER5_LAW_PROMPT.md. Each is a closed form or an enumeration,
cross-checked by simulation through the reference router (neo4d/kit/router5_ref.h - the judge's oracle, not a law).

    python -m neo4d.router5_math   -> results/ROUTER5_MATH.md
"""
from __future__ import annotations

import ctypes
import itertools
import math
import random
import subprocess
import sys
import tempfile
from fractions import Fraction as Fr
from pathlib import Path

from neo4d import PKG, REPO
from neo4d.kit_scaling import gl_order, p_pin


def rank(vs):
    basis = []
    for v in vs:
        for b in basis:
            v = min(v, v ^ b)
        if v:
            basis.append(v)
    return len(basis)


def answered_as_they_come(n, k):
    """Affine truth, k distinct random cases: the share of all 2^n queries answered (= the affine span's size)."""
    tot = Fr(0)
    for S in itertools.combinations(range(2 ** n), k):
        tot += 2 ** rank([s ^ S[0] for s in S[1:]])
    return tot / (2 ** n * math.comb(2 ** n, k))


def passive(n):
    return sum(1 - p_pin(n, k) for k in range(2 ** n + 1))


def outside(n, k):
    """A random permutation as the truth, n + 1 span-aware cases + validation: P(right, refused, wrong) per query."""
    N, k0 = 2 ** n, n + 1
    accept = Fr(math.prod(N - 2 ** i for i in range(n)), math.prod(N - 1 - i for i in range(n)))
    for j in range(k - k0):
        accept *= Fr(1, N - k0 - j)
    rest = N - k
    return accept * (Fr(k, N) + Fr(rest, N) * Fr(1, rest)), 1 - accept, accept * Fr(rest - 1, N)


def reference():
    d = Path(tempfile.mkdtemp(prefix="r5m_"))
    (d / "k.c").write_text(f'#include "{PKG / "kit" / "router5_ref.h"}"\n'
                           "int64_t route5(int64_t x){ return ref5((uint64_t)x); }\n")
    subprocess.run(["cc", "-O2", "-shared", "-fPIC", "-o", str(d / "k.so"), str(d / "k.c")], check=True)
    f = ctypes.CDLL(str(d / "k.so")).route5
    f.argtypes, f.restype = [ctypes.c_int64], ctypes.c_int64

    def route(F, A, q):
        x = 0
        for i in range(1, 6):
            x |= (F[i] ^ F[0]) << (10 * (i - 1)) | (A[i] ^ A[0]) << (10 * (i - 1) + 5)
        v = int(f(x | (q ^ F[0]) << 50)) & 63
        return None if v >= 32 else v ^ A[0]
    return route


def affine32(rng):
    while True:
        cols = [rng.randrange(32) for _ in range(5)]
        if rank(cols) == 5:
            break
    c = rng.randrange(32)
    return [c ^ (cols[0] * (v & 1)) ^ (cols[1] * (v >> 1 & 1)) ^ (cols[2] * (v >> 2 & 1)) ^ (cols[3] * (v >> 3 & 1))
            ^ (cols[4] * (v >> 4 & 1)) for v in range(32)]


def span_aware(rng, k):
    F = [rng.randrange(32)]
    while len(F) < k:
        f = rng.randrange(32)
        if f in F:
            continue
        r = rank([x ^ F[0] for x in F[1:]])
        if r == 5 or rank([x ^ F[0] for x in F[1:]] + [f ^ F[0]]) > r:
            F.append(f)
    return F


def main() -> int:
    rng = random.Random(2026)
    route = reference()
    T = 20_000
    rows = []
    a16, a32 = answered_as_they_come(4, 5), answered_as_they_come(5, 6)
    sim = {"come": [0, 0], "aware": [0, 0]}
    for _ in range(T):
        h = affine32(rng)
        for key, F in (("come", rng.sample(range(32), 6)), ("aware", span_aware(rng, 6))):
            A = [h[f] for f in F]
            for q in range(32):
                g = route(F, A, q)
                sim[key][0] += g is not None
                sim[key][1] += g is not None and g != h[q]
    bad = sim["come"][1] + sim["aware"][1] + (sim["aware"][0] != 32 * T)
    bad += abs(sim["come"][0] / (32 * T) - float(a32)) > 0.01
    out_sim = {}
    for k in (6, 7, 8, 9):
        c = [0, 0, 0]
        for _ in range(T):
            p = rng.sample(range(32), 32)
            F = span_aware(rng, 6)
            extra = rng.sample([f for f in range(32) if f not in F], k - 6)
            A = [p[f] for f in F]
            ok = all(route(F, A, f) == p[f] for f in extra)
            q = rng.randrange(32)
            g = route(F, A, q) if ok else None
            if g is not None and q in extra:
                g = p[q]
            c[0 if g == p[q] else (1 if g is None else 2)] += 1
        out_sim[k] = [x / T for x in c]
        r, f, w = outside(5, k)
        sd = math.sqrt(float(w) * (1 - float(w)) / T) + 1e-9
        bad += abs(out_sim[k][2] - float(w)) > 6 * sd
    out = ["# The 32-kind router's numbers, exact", "",
           "Generated by `neo4d/router5_math.py`; every exact value cross-checked by simulation through the reference "
           f"router ({T:,} trials each).", "",
           "## Sixteen kinds against thirty-two", "",
           "| | 16 kinds, GF(2)^4 | **32 kinds, GF(2)^5** |", "|---|---|---|",
           f"| affine relabellings | {16 * gl_order(4):,} | **{32 * gl_order(5):,}** |",
           "| examples that pin one | 5 | **6** |",
           "| bits for the examples and the query | 44 (affine) | **65 affine - 55 once the body moves example 1 to the origin** |",
           f"| k cases taken as they come pin it | 8/13 = {8 / 13:.1%} | **{p_pin(5, 6)} = {float(p_pin(5, 6)):.1%}** |",
           f"| ... share of all queries then answered (affine truth, never wrong) | {a16} = {float(a16):.1%} | "
           f"**{a32} = {float(a32):.1%}** (simulated {sim['come'][0] / (32 * T):.1%}, wrong {sim['come'][1]}) |",
           f"| each case a new direction - what HARVEST delivers | 100% | **100%** (simulated {sim['aware'][0] / (32 * T):.1%}, "
           f"wrong {sim['aware'][1]}) |",
           f"| cases drawn at random until pinned, expected | {passive(4)} = {float(passive(4)):.2f} | "
           f"**{passive(5)} = {float(passive(5)):.2f}** |",
           "| suite runs at HARVEST's 4 per example, new directions | 20 | **24** |", "",
           "## A truth outside the structure - a random permutation of the 32 codes", "",
           "Six span-aware cases fit; k - 6 more must agree with the fit or the body refuses (the same router).", "",
           "| k | exact right | exact refused | **exact wrong** | simulated wrong |", "|---|---|---|---|---|"]
    for k in (6, 7, 8, 9):
        r, f, w = outside(5, k)
        out.append(f"| {k} | {r} = {float(r):.2%} | {f} = {float(f):.2%} | **{w} = {float(w):.3%}** | "
                   f"{out_sim[k][2]:.3%} |")
    r16 = Fr(5, 13)
    out += ["", f"At 16 kinds the same row reads 5/13 = {float(r16):.1%} wrong from five examples: a bigger space does not "
            "make an accidental fit rarer - each validation example still cuts it by about the number of codes left.", "",
            f"**Checks failed: {bad}.**"]
    (REPO / "results" / "ROUTER5_MATH.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return int(bad != 0)


if __name__ == "__main__":
    sys.exit(main())
