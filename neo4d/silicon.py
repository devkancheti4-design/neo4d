"""The routers on silicon - route4d5 (16 kinds) and route5 (32 kinds): what the machine code is, and what the
hardware counters say.

    1  STATIC   disassemble the compiled router: instructions, conditional branches, memory loads and stores. No
                memory instruction means no data-cache access, so no cache miss; no conditional branch means nothing
                to mispredict - proven from the code itself, not sampled.
    2  COUNTERS 100,000 queries per pass, generated in registers, x 1,000 passes, with and without the router;
                instructions retired and cycles from the CPU's own counters (macOS `/usr/bin/time -l`, Linux
                `perf stat`), the empty loop subtracted: instructions, cycles and IPC per call.

    python -m neo4d.silicon   -> results/SILICON.md
"""
from __future__ import annotations

import platform
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from neo4d import KERNELS, REPO

BENCH = r'''
#define ROUTER {fn}
#define MASK {mask}ULL
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <time.h>
int64_t ROUTER(int64_t x);
int main(int argc, char **argv){
    int with_router = atoi(argv[1]); long passes = atol(argv[2]);
    uint64_t s = 88172645463325252ULL, sink = 0;
    struct timespec t0, t1; clock_gettime(CLOCK_MONOTONIC, &t0);
    for (long p = 0; p < passes; p++)
        for (long i = 0; i < 100000; i++){
            s ^= s << 13; s ^= s >> 7; s ^= s << 17;
            uint64_t x = s & MASK;
            sink += with_router ? (uint64_t)ROUTER((int64_t)x) : x;
        }
    clock_gettime(CLOCK_MONOTONIC, &t1);
    fprintf(stderr, "wall %.6f sink %llu\n", (t1.tv_sec - t0.tv_sec) + (t1.tv_nsec - t0.tv_nsec) * 1e-9,
            (unsigned long long)(sink & 0xff));
    return 0;
}
'''


def static(obj: Path) -> dict:
    if shutil.which("otool"):
        asm = subprocess.run(["otool", "-tv", str(obj)], capture_output=True, text=True).stdout
        ins = [l for l in asm.splitlines() if re.match(r"^[0-9a-f]+\s", l)]
    else:
        asm = subprocess.run(["objdump", "-d", "--no-show-raw-insn", str(obj)], capture_output=True, text=True).stdout
        ins = [l for l in asm.splitlines() if re.match(r"^\s+[0-9a-f]+:\s", l)]
    text = "\n".join(ins)
    cond = len(re.findall(r"\sb\.[a-z]{2}\s|\scbn?z\s|\stbn?z\s|\sj(?!mp)[a-z]{1,3}\s", text))
    mem = len(re.findall(r"\s(ldr|str|ldp|stp|ldur|stur)[a-z]*\s|\smov[a-z]*\s+[^,\n]*\(|\(%r[sb]p\)", text))
    return {"instructions": len(ins), "conditional_branches": cond, "memory_ops": mem, "bytes": len(ins) * 4}


def counters(exe: Path, with_router: int, passes: int) -> dict:
    if platform.system() == "Darwin":
        r = subprocess.run(["/usr/bin/time", "-l", str(exe), str(with_router), str(passes)], capture_output=True,
                           text=True)
        t = r.stderr
        return {"wall": float(re.search(r"wall ([\d.]+)", t).group(1)),
                "instructions": int(re.search(r"(\d+)\s+instructions retired", t).group(1)),
                "cycles": int(re.search(r"(\d+)\s+cycles elapsed", t).group(1))}
    r = subprocess.run(["perf", "stat", "-x,", "-e", "instructions,cycles", str(exe), str(with_router), str(passes)],
                       capture_output=True, text=True)
    t = r.stderr
    vals = {m.group(2): int(m.group(1)) for m in re.finditer(r"^(\d+),[^,]*,(instructions|cycles)", t, re.M)}
    return {"wall": float(re.search(r"wall ([\d.]+)", t).group(1)), **vals}


ROUTERS = (("route4d5", "router4d5.c", "0xFFFFFFFFFFF", "16 kinds"), ("route5", "router5.c", "0x7FFFFFFFFFFFFF", "32 kinds"))


def measure(fn: str, src: str, mask: str, passes: int) -> dict:
    d = Path(tempfile.mkdtemp(prefix="neo4d_si_"))
    obj = d / "r.o"
    subprocess.run(["cc", "-O2", "-c", "-o", str(obj), str(KERNELS / src)], check=True)
    st = static(obj)
    (d / "sat.c").write_text(BENCH.replace("{fn}", fn).replace("{mask}", mask))
    exe = d / "sat"
    subprocess.run(["cc", "-O2", "-o", str(exe), str(d / "sat.c"), str(obj)], check=True)
    w, b = counters(exe, 1, passes), counters(exe, 0, passes)
    n = passes * 100_000
    st.update(di=(w["instructions"] - b["instructions"]) / n, dc=(w["cycles"] - b["cycles"]) / n,
              ns=(w["wall"] - b["wall"]) / n * 1e9, n=n)
    return st


def main(passes: int = 1000) -> int:
    cpu = (subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True).stdout.strip()
           if platform.system() == "Darwin" else platform.processor())
    res = [(fn, kinds, measure(fn, src, mask, passes)) for fn, src, mask, kinds in ROUTERS]
    head = "| | " + " | ".join(f"`{fn}` ({kinds})" for fn, kinds, _ in res) + " |"
    sep = "|---|" + "---|" * len(res)
    row = lambda label, f: f"| {label} | " + " | ".join(f(st) for _, _, st in res) + " |"
    out = ["# The routers on silicon", "", f"Generated by `neo4d/silicon.py` on {cpu}, `cc -O2`.", "",
           "## The machine code", "", head, sep,
           row("instructions", lambda st: f"{st['instructions']} ({st['bytes']} bytes - resident in L1 instruction cache)"),
           row("conditional branches", lambda st: f"**{st['conditional_branches']}** - nothing to mispredict"),
           row("memory loads / stores", lambda st: f"**{st['memory_ops']}** - no data-cache access, so no cache miss"), "",
           "## The hardware counters", "",
           f"{res[0][2]['n']:,} calls per router (100,000 queries per pass, generated in registers, x {passes:,}); the "
           "empty loop subtracted.", "", head.replace("| |", "| per router call |", 1), sep,
           row("instructions", lambda st: f"{st['di']:.1f}"), row("cycles", lambda st: f"{st['dc']:.2f}"),
           row("**IPC**", lambda st: f"**{st['di'] / st['dc']:.2f}**"),
           row("time", lambda st: f"**{st['ns']:.2f} ns**")]
    (REPO / "results" / "SILICON.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return int(any(st["conditional_branches"] or st["memory_ops"] for _, _, st in res))


if __name__ == "__main__":
    sys.exit(main())
