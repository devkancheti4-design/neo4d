"""neo4d by exact math - every number a closed form over the group, checked against brute force and the measurements.

No estimates, no training: fractions computed from the structure of GA(4, F2), each confirmed by enumeration or
by a fresh simulation, next to what the earlier runs measured.

    1  the version space after examples of rank r          prod_{i=r}^{3} (16 - 2^i)        brute force
    2  how many examples pin a relabelling                   affine 5, ring 1, unrestricted 15  enumeration
    3  random examples: the chance five pin it               exact over all C(16,5) case sets   enumeration
    4  a truth outside the structure (random permutation)    right 3/13, refused 5/13, wrong 5/13   simulation
    5  a ghost query (rank-3 span, query outside)            any guess right <= 1/8; neo4d wrong 0
    6  verification cost of learning one relabelling         test runs: 20 vs 60 vs 64       measured constants

    python -m neo4d.exactmath   -> results/EXACT_MATH.md
"""
from __future__ import annotations

import ctypes
import itertools
import math
import random
import sys
from fractions import Fraction as Fr

from neo4d import REPO, build_kernel
from neo4d import edge_cases as E


def rank(vecs):
    return E.rank(vecs)


def survivors_formula(r: int) -> int:
    return math.prod(16 - 2 ** i for i in range(r, 4))


def main() -> int:
    rng = random.Random(2026)
    out = ["# neo4d by exact math", "",
           "Generated by `neo4d/exactmath.py`. Every value below is a closed form over the affine group of GF(2)^4, "
           "written as an exact fraction, and checked - by brute force over all 322,560 maps, by enumeration, or by a "
           "fresh simulation - next to what the earlier runs measured.", ""]
    bad = 0

    # 1 - the version space
    GL = survivors_formula(0)
    out += ["## 1. The version space", "",
            f"|GL(4,2)| = 15 x 14 x 12 x 8 = **{GL:,}**; the affine group = 16 x {GL:,} = **{16 * GL:,}** relabellings.", "",
            "| rank of the example differences | maps surviving = prod (16 - 2^i), i = r..3 | brute force (300 random example sets) | answers open outside the span = 16 - 2^r |",
            "|---|---|---|---|"]
    for r in range(5):
        seen = set()
        for _ in range(300):
            ex, h, span, F1 = E.examples_of_rank(r, r + 1, rng)
            seen.add(bin(E.survivors(ex)).count("1"))
        ok = seen == {survivors_formula(r)}
        bad += not ok
        out.append(f"| {r} | {survivors_formula(r):,} | {sorted(seen)} {'OK' if ok else 'MISMATCH'} | "
                   f"{16 - 2 ** r if r < 4 else '- (determined)'} |")

    # 2 - how many examples pin a relabelling
    out += ["", "## 2. How many worked examples pin a whole relabelling of the 16 kinds", "",
            "| structure | relabellings | examples that pin one | why |", "|---|---|---|---|",
            "| ring of 16 (static fluidnet) | 16 | **1** | one example fixes the shift |",
            f"| affine GF(2)^4 (neo4d) | {16 * GL:,} | **5** | one fixes the shift, four independent differences fix M |",
            f"| unrestricted (any permutation) | {math.factorial(16):,} | **15** | after k examples (16-k)! remain; 1 only at k = 15 |",
            "", f"neo4d covers {16 * GL // 16:,}x the ring's relabellings for 4 more examples, and needs **1/3** of the "
            "examples a structure-free learner needs for a full relabelling (5 vs 15)."]

    # 3 - random examples: the chance five pin it
    def affinely_spanning(S):
        S = list(S)
        return rank([s ^ S[0] for s in S[1:]]) == 4
    total = math.comb(16, 5)
    span5 = sum(affinely_spanning(S) for S in itertools.combinations(range(16), 5))
    p5 = Fr(span5, total)
    rows3 = []
    for k in range(5, 9):
        tk = math.comb(16, k)
        sk = sum(affinely_spanning(S) for S in itertools.combinations(range(16), k))
        rows3.append((k, Fr(sk, tk), sk, tk))
    out += ["", "## 3. Examples taken at random - the exact chance they pin the relabelling", "",
            "Enumerated over every set of k distinct cases:", "",
            "| k distinct random cases | sets that span (pin the map) | probability |", "|---|---|---|"]
    for k, pk, sk, tk in rows3:
        out.append(f"| {k} | {sk:,} of {tk:,} | **{pk}** = {float(pk):.4f} |")
    out += ["", f"Chosen span-aware (HARVEST's NEW_SPAN, PICK's ranking), five always pin it: probability **1**. Taken "
            f"at random, five pin it with probability {p5} = {float(p5):.4f} - the gap HARVEST closes."]

    # 4 - a truth outside the structure
    p_fit = Fr(16 * 15 * 14 * 12 * 8, 16 * 15 * 14 * 13 * 12)
    p_right = p_fit * (Fr(5, 16) + Fr(11, 16) * Fr(1, 11))
    p_ref = 1 - p_fit
    p_wrong = p_fit * Fr(11, 16) * Fr(10, 11)
    f = ctypes.CDLL(str(build_kernel("router4d5"))).route4d5
    f.argtypes, f.restype = [ctypes.c_int64], ctypes.c_int64
    n, c = 200_000, {"right": 0, "refused": 0, "wrong": 0}
    for _ in range(n):
        while True:
            Fs = rng.sample(range(16), 5)
            if affinely_spanning(Fs):
                break
        p = list(range(16))
        rng.shuffle(p)
        q = rng.randrange(16)
        x = sum(fk << (8 * i) | p[fk] << (8 * i + 4) for i, fk in enumerate(Fs)) | q << 40
        v = int(f(x)) & 31
        c["refused" if v >= 16 else ("right" if v == p[q] else "wrong")] += 1
    out += ["", "## 4. A truth outside the structure - a random permutation of the 16 codes", "",
            "Five examples with affinely independent cases, query uniform over the 16 codes. An affine map fits "
            "exactly when the four action differences are independent: (12 x 8) / (13 x 12) = **8/13**. If it fits, the "
            "router answers - right on the 5 example cases, and on each other case right only if the permutation "
            "happens to agree (1 in 11). If it does not fit, it refuses everything.", "",
            "| | exact | = | fresh simulation, 200,000 | measured before (`results/ROBUSTNESS.md`, 20,000) |",
            "|---|---|---|---|---|",
            f"| right | **{p_right}** | {float(p_right):.4%} | {c['right'] / n:.4%} | 22.99% |",
            f"| refused | **{p_ref}** | {float(p_ref):.4%} | {c['refused'] / n:.4%} | 38.44% |",
            f"| wrong | **{p_wrong}** | {float(p_wrong):.4%} | {c['wrong'] / n:.4%} | 38.57% |", "",
            "Exact for a truth inside the structure: wrong = **0** (sections 1 and the judges). Outside it, the 5/13 is "
            "the price of answering when five points happen to fit - stated, not hidden."]
    sd = math.sqrt(float(p_wrong) * (1 - float(p_wrong)) / n)
    bad += abs(c["wrong"] / n - float(p_wrong)) > 5 * sd

    # 5 - ghost queries
    out += ["", "## 5. A ghost query - examples spanning rank 3, the query outside the span", "",
            "8 affine maps survive and give 8 different answers, each equally likely when the truth is uniform over the "
            "class. Any rule that answers is right with probability at most **1/8 = 12.5%**; neo4d refuses, so it is "
            "wrong with probability **0**. Measured (`results/ADVERSARIAL.md`): neo4d refused 100%, a nearest-example "
            "heuristic was right 6.5% (below the 1/8 ceiling - its guess is not always one of the 8)."]

    # 6 - verification cost
    runs = 4
    out += ["", "## 6. The verification cost of learning one whole relabelling", "",
            f"Each worked example costs {runs} test-suite runs (caught, restored, and both re-checked - measured, "
            "`results/HARVEST_PICK.md`):", "",
            "| learner | examples | suite runs | relative |", "|---|---|---|---|",
            f"| neo4d (affine, span-aware) | 5 | **{5 * runs}** | 1 |",
            f"| structure-free (any permutation) | 15 | {15 * runs} | {Fr(15, 5)}x |",
            f"| test every kind directly | 16 | {16 * runs} | {Fr(16, 5)}x |", "",
            "Measured on click: **20** suite runs, both secret renumberings. One router decision after that: ~4 ns "
            "(`results/SILICON.md`); one click suite run: ~3.7 s - the router is not where the time goes; the "
            "examples are, and the structure cuts them to a third."]

    out += ["", f"**Checks failed: {bad}.**"]
    (REPO / "results" / "EXACT_MATH.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return int(bad != 0)


if __name__ == "__main__":
    sys.exit(main())
