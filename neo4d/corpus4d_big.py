"""fluidfix's vocabulary renumbered 4D-natively, tested on every real fix on disk - fast, decisions only.

VOCABULARY  fluidfix 0.16.0's nine shipped classes (kinds 0-3, 8-12) + fluidnet's two taught demo classes
            (wrong-attribute-sibling as kind 4, len-as-last-index as kind 7): eleven kinds.
NUMBERINGS  as shipped     act = (kind + 5) mod 16    - fluidfix's router convention, a ring
            4D-native      act = kind XOR 5           - the same acts, codes placed in GF(2)^4
CORPUS      every one-line replacement in BugsInPy, Defects4J and Defects4C (1,729 bugs), fluid-router's 33-bug
            corpus, and the click race's reconstructed bugs. A DECISION is one (fixed line, kind) where that kind's
            class generates the real fixed line from the real buggy line.
LAWS        frozen   the old kind -> act table, blind to renumbering
            ring     fluid-router verbatim, ONE worked example (kind 0 -> its act)
            route4d  your affine GF(2)^4 law, THREE worked examples drawn from the other kinds (5 draws per decision)
FAMILIES    every renumbering of the act codes: ring (16), XOR (16), 8-cell symmetries (384), affine (3,000 sampled)

    python3 corpus4d_big.py   -> results/CORPUS4D_BIG.md
"""
from __future__ import annotations

import json
import random
import re
import sys
from collections import Counter
from pathlib import Path

from neo4d import classes as C
from neo4d import generalize as G
from neo4d import realfix as RF
from neo4d.corpus4d import REFUSE, route4d, ring_route

from neo4d import REPO as ROOT, KERNELS


def vocabulary():
    cls = {c.kind: c for c in C.shipped()}
    demo = {c.name: c for c in C.demo_taught()}
    cls[4] = demo["wrong-attribute-sibling"]
    cls[7] = demo["len-as-last-index"]
    return dict(sorted(cls.items()))


def corpus_pairs():
    """(source, buggy line, fixed line) for every one-line replacement in every real corpus on disk."""
    out = []
    for corpus, _lang, bid, hs in RF.load_bugsinpy() + RF.load_defects4j() + RF.load_defects4c():
        for _f, m, p in hs:
            if len(m) == 1 and len(p) == 1:
                out.append((corpus, m[0], p[0]))
    fr = ROOT / "bench" / "fluid-router" / "benchmark"
    for b, ok in zip(json.load(open(fr / "bugs.json")), json.load(open(fr / "valid.json"))):
        if ok:
            out.append(("fluid-router", b["mutated"], b["orig"]))
    from neo4d import green
    for f, line, orig, bug, how in green.BUGS.values():
        out.append(("click race", bug, orig))
    return out


def decisions(vocab):
    out = []
    for src, buggy, fixed in corpus_pairs():
        for k, c in vocab.items():
            cands = c.candidates(buggy, 1, [buggy])
            if any(RF.norm_ws(x) == RF.norm_ws(fixed) for x in cands):
                out.append((src, k))
    return out


def run(decs, kinds, act_of, family, rng, sample=None, draws=5):
    H = family if sample is None or len(family) <= sample else family[rng.sample(range(len(family)), sample)]
    t = {law: Counter() for law in ("frozen", "ring", "route4d")}
    for g in H:
        for _src, k in decs:
            want = int(g[act_of[k]])
            t["frozen"]["right" if act_of[k] == want else "wrong"] += 1
            r = ring_route(0, int(g[act_of[0]]), k)                 # fluidfix's worked example: kind 0
            t["ring"]["right" if r == want else "wrong"] += 1
            others = [f for f in kinds if f != k]
            for _ in range(draws):
                ex = [(f, int(g[act_of[f]])) for f in rng.sample(others, 3)]
                r = route4d(ex, k)
                t["route4d"]["refused" if r == REFUSE else ("right" if r == want else "wrong")] += 1
    return t


def main() -> int:
    rng = random.Random(2026)
    vocab = vocabulary()
    kinds = list(vocab)
    pairs = corpus_pairs()
    decs = decisions(vocab)
    by_src = Counter(s for s, _ in decs)
    by_kind = Counter(vocab[k].name for _, k in decs)
    print(f"  {len(pairs)} real one-line fixes, {len(decs)} decisions: {dict(by_src)}", flush=True)
    numberings = {"as shipped: act = (kind + 5) mod 16": {k: (k + 5) % 16 for k in kinds},
                  "4D-native: act = kind XOR 5": {k: k ^ 5 for k in kinds}}
    for name, a in numberings.items():
        assert len(set(a.values())) == len(a), name
    fams = {"ring (16)": (G.ring16(), None), "XOR (16)": (G.xor16(), None),
            "8-cell symmetries (384)": (G.cube16(), None), "affine (3,000 of 322,560)": (G.affine16(), 3000)}
    out = ["# fluidfix's vocabulary renumbered 4D-natively, on every real fix on disk", "",
           f"Generated by `corpus4d_big.py`. **{len(pairs):,} real one-line fixes** "
           f"(BugsInPy, Defects4J, Defects4C, fluid-router's corpus, the click race); **{len(decs)} decisions** - "
           "a real fixed line generated by a vocabulary class from the real buggy line: "
           + ", ".join(f"{s} {n}" for s, n in by_src.items()) + ". By class: "
           + ", ".join(f"{k} {n}" for k, n in by_kind.most_common()) + ".", "",
           f"Vocabulary: eleven kinds - fluidfix's nine shipped classes and fluidnet's two taught demo classes. "
           "route4d gets three worked examples drawn at random from the other ten kinds (five draws per decision); "
           "the ring router gets fluidfix's one (kind 0). % of decisions right / refused / **wrong**.", ""]
    for name, act_of in numberings.items():
        out += [f"## Numbered {name}", "",
                "| renumbering family | frozen table | ring router (static fluidnet), 1 example | route4d (4D), 3 examples |",
                "|---|---|---|---|"]
        for fname, (H, smp) in fams.items():
            t = run(decs, kinds, act_of, H, rng, smp)
            cell = lambda c: (f"{100*c['right']/sum(c.values()):.0f} / {100*c['refused']/sum(c.values()):.0f} / "
                              f"**{100*c['wrong']/sum(c.values()):.0f}**")
            out.append(f"| {fname} | {cell(t['frozen'])} | {cell(t['ring'])} | {cell(t['route4d'])} |")
            print(f"  {name[:12]:12} {fname:26} ring {cell(t['ring'])}   route4d {cell(t['route4d'])}", flush=True)
        out.append("")
    (ROOT / "results/CORPUS4D_BIG.md").write_text("\n".join(out) + "\n")
    print("\n" + "\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
