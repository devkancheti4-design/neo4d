"""Kit test 2 - one numbering for every language? QuixBugs' 40 programs exist in Python AND Java, same bug in each.

For each program and language, the buggy file against the correct one, after dropping what is not code (blank lines,
comments, docstrings, imports, package lines; whitespace ignored). Then:

    one-line     the fix replaces exactly one line
    generated    neo4d's vocabulary (the QuixBugs run's: fluidfix's nine shipped classes + the two taught demo
                 classes) proposes the fixed line from the buggy line, exactly
    same kind    the class that generates it is the same in both languages - the same 4-bit code

Patch level only: there is no Java runtime on this machine, so the Java tests are not run. The Python side is run for
real in results/QUIXBUGS.md.

    python -m neo4d.kit_language   -> results/KIT_LANGUAGE.md
"""
from __future__ import annotations

import ast
import difflib
import re
import sys

from neo4d import REPO
from neo4d.quixbugs import QB, VOCAB, programs


def _doc_lines(src):
    drop = set()
    for n in ast.walk(ast.parse(src)):
        if isinstance(n, ast.Expr) and isinstance(n.value, ast.Constant) and isinstance(n.value.value, str):
            drop.update(range(n.lineno, n.end_lineno + 1))
    return drop


def code_lines(src, java):
    drop = set() if java else _doc_lines(src)
    out = []
    for i, line in enumerate(src.split("\n"), 1):
        s = line.strip()
        if i in drop or not s or s.startswith(("#", "//", "import ", "package ", "/*", "*")):
            continue
        out.append(line)
    return out


def key(line, java):
    if not java:
        line = re.sub(r"\s+#.*$", "", line)
    return re.sub(r"\s+", "", line)


def fix_of(name, java):
    sub = ("java_programs", "correct_java_programs") if java else ("python_programs", "correct_python_programs")
    fn = f"{name.upper()}.java" if java else f"{name}.py"
    b = code_lines((QB / sub[0] / fn).read_text(), java)
    c = code_lines((QB / sub[1] / fn).read_text(), java)
    ops = [o for o in difflib.SequenceMatcher(None, [key(x, java) for x in b], [key(x, java) for x in c],
                                              autojunk=False).get_opcodes() if o[0] != "equal"]
    if all(o[0] == "insert" for o in ops):
        return "omission", None, None
    if len(ops) != 1 or ops[0][0] != "replace" or ops[0][2] - ops[0][1] != 1 or ops[0][4] - ops[0][3] != 1:
        return "multi-line", None, None
    return "one-line", b[ops[0][1]], c[ops[0][3]]


def generate(buggy, fixed, java):
    for k, cls in VOCAB.items():
        if any(key(x, java) == key(fixed, java) for x in cls.candidates(buggy, 1, [buggy])):
            return k, cls.name
    return None


def main() -> int:
    rows = []
    for name in programs():
        r = {"program": name}
        for lang, java in (("py", False), ("java", True)):
            shape, b, f = fix_of(name, java)
            g = generate(b, f, java) if shape == "one-line" else None
            r[lang] = (shape, g, b, f)
        rows.append(r)
    count = lambda lang, pred: sum(pred(r[lang]) for r in rows)
    one = lambda x: x[0] == "one-line"
    gen = lambda x: x[1] is not None
    both = [r for r in rows if gen(r["py"]) and gen(r["java"])]
    same = [r for r in both if r["py"][1][0] == r["java"][1][0]]
    only_py = [r for r in rows if gen(r["py"]) and not gen(r["java"])]
    only_java = [r for r in rows if gen(r["java"]) and not gen(r["py"])]
    shape_agree = sum(r["py"][0] == r["java"][0] for r in rows)
    out = ["# Kit 2 - one numbering across languages (QuixBugs, Python and Java)", "",
           "Generated by `neo4d/kit_language.py`. The same 40 bugs in both languages; each buggy file against its "
           "correct version, with comments, docstrings, imports and whitespace ignored. Patch level: no Java runtime "
           "here, so the Java tests are not run.", "",
           "| | Python | Java |", "|---|---|---|",
           f"| the fix replaces one line | {count('py', one)} | {count('java', one)} |",
           f"| the fix only ADDS a line (missing logic) | {count('py', lambda x: x[0] == 'omission')} | "
           f"{count('java', lambda x: x[0] == 'omission')} |",
           f"| the fix spans several lines | {count('py', lambda x: x[0] == 'multi-line')} | "
           f"{count('java', lambda x: x[0] == 'multi-line')} |",
           f"| **the vocabulary generates the fix exactly** | **{count('py', gen)}** | **{count('java', gen)}** |", "",
           f"Fix shape agrees across the languages on {shape_agree} of 40 programs. Generated in both: **{len(both)}**, "
           f"by the same class - the same 4-bit kind - in **{len(same)} of {len(both)}**. Python only: {len(only_py)}; "
           f"Java only: {len(only_java)}.", "",
           "| program | Python | Java | kind |", "|---|---|---|---|"]
    for r in rows:
        if gen(r["py"]) or gen(r["java"]):
            cell = lambda x: f"`{x[2].strip()}` -> `{x[3].strip()}`" if gen(x) else f"not generated ({x[0]})"
            kinds = {x[1][1] for x in (r["py"], r["java"]) if gen(x)}
            out.append(f"| {r['program']} | {cell(r['py'])} | {cell(r['java'])} | {', '.join(sorted(kinds))} |")
    if only_py or only_java:
        out += ["", "Where the languages differ:", ""]
        for r in only_py + only_java:
            other = "java" if r in only_py else "py"
            x = r[other]
            what = f"`{x[2].strip()}` -> `{x[3].strip()}`" if x[0] == "one-line" else x[0]
            out.append(f"- {r['program']}, {'Java' if other == 'java' else 'Python'}: {what}")
    out += ["", "Exact text undercounts: in Python, next_permutation and levenshtein are repaired by their own tests in "
            "`results/QUIXBUGS.md` with an equivalent rewrite (`perm[j] > perm[i]` for the reference's "
            "`perm[i] < perm[j]`; `0 +` for the reference dropping `1 +`). Counting next_permutation, the same kind "
            "fixes the same bug in both languages in 4 programs; next_palindrome is the one real gap - "
            "len-as-last-index rewrites `len(x)`, and Java spells it `x.length`."]
    out += ["", "**What this shows.** A class is a token rewrite, so where a bug is written with the same tokens in "
            "both languages the same kind generates its fix; the code-to-kind map carries over. It does not carry "
            "where the languages spell the construct differently, and nothing in the vocabulary generates an added "
            "line - those need fluidnet's omission path."]
    (REPO / "results" / "KIT_LANGUAGE.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
