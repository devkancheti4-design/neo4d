"""Kit test 4 - federation: two installations, each numbering the 16 fault kinds its own way, merge what they know.

Party A knows the repair act for all 16 kinds, in A's numbering. Party B numbers the same kinds differently and knows
nothing yet. They exchange only k ANCHORS - (A's code, B's code) for faults both have met - no source, no tests, no
act tables. route4d5 learns B's numbering from A's on those anchors, and B translates A's whole act table:
act_B[M(a)] = act_A[a] where the router answers, refused where it does not.

    affine numberings       both are affine relabellings (what neo4d's own numbering is up to): M is affine
    arbitrary numbering     B numbers kinds at random: M is a random permutation - outside the structure
    anchors                 random (whatever faults the two happened to share) or span-aware (A picks anchors
                            whose codes are a new direction each); k = 5, plus validation anchors k = 6..8 that
                            must agree with the fit or B refuses everything (the same router, no new law)

Exact values: random anchors answer the affine span of their codes (enumerated over every 5-subset); arbitrary
numbering matches degeneracy.exact_validation.

    python -m neo4d.kit_federation   -> results/KIT_FEDERATION.md
"""
from __future__ import annotations

import itertools
import math
import random
import sys
from collections import Counter
from fractions import Fraction as Fr

from neo4d import REPO
from neo4d import edge_cases as E
from neo4d.degeneracy import exact_validation
from neo4d.inductive import router, span_aware

H = E.H


def inverse(p):
    q = [0] * 16
    for i, v in enumerate(p):
        q[v] = i
    return q


def exact_random_anchors():
    """Affine M, 5 random distinct anchor codes: B can translate exactly the affine span of A's anchor codes."""
    tot = Fr(0)
    for S in itertools.combinations(range(16), 5):
        tot += 2 ** E.rank([s ^ S[0] for s in S[1:]])
    return tot / (16 * math.comb(16, 5))


def trial(rng, route, affine_b, anchors, k):
    NA = list(map(int, H[rng.randrange(len(H))]))
    NB = list(map(int, H[rng.randrange(len(H))])) if affine_b else rng.sample(range(16), 16)
    to_kind = inverse(NA)
    M = [NB[to_kind[a]] for a in range(16)]                     # A's code -> B's code for the same kind
    acts_a = [rng.randrange(16) for _ in range(16)]             # A's knowledge, in A's numbering
    truth_b = [0] * 16
    for a in range(16):
        truth_b[M[a]] = acts_a[a]
    codes = span_aware(rng, 5) if anchors == "span-aware" else rng.sample(range(16), 5)
    extra = rng.sample([a for a in range(16) if a not in codes], k - 5)
    ex = [(a, M[a]) for a in codes]
    ok = all(route(ex, a) == M[a] for a in extra)
    c = Counter()
    for a in range(16):
        b = route(ex, a) if ok else None
        if b is not None and a in extra:
            b = M[a]                                            # an anchor is known exactly
        if b is None:
            c["refused"] += 1
        else:
            c["right" if acts_a[a] == truth_b[b] and b == M[a] else "wrong"] += 1
    return c


def main() -> int:
    rng = random.Random(2026)
    route = router()
    n = 50_000
    rows, bad = [], 0
    ex_rand = exact_random_anchors()
    for affine_b, anchors, k in ((True, "random", 5), (True, "span-aware", 5),
                                 (False, "span-aware", 5), (False, "span-aware", 6),
                                 (False, "span-aware", 7), (False, "span-aware", 8)):
        c = Counter()
        for _ in range(n):
            c.update(trial(rng, route, affine_b, anchors, k))
        sh = {x: c[x] / (16 * n) for x in ("right", "refused", "wrong")}
        if affine_b:
            exact = (ex_rand if anchors == "random" else Fr(1), None, Fr(0))
            bad += c["wrong"] != 0
            bad += abs(sh["right"] - float(exact[0])) > 0.005
        else:
            r, f, w = exact_validation(k)
            exact = (r, f, w)
            sd = math.sqrt(float(w) * (1 - float(w)) / n) + 1e-9
            bad += abs(sh["wrong"] - float(w)) > 6 * sd + 0.002
        rows.append(("affine" if affine_b else "arbitrary", anchors, k, sh, exact))
        print(f"  {rows[-1][0]:9} {anchors:10} k={k}  {sh}", flush=True)
    out = ["# Kit 4 - federation: merging two numberings from anchors alone", "",
           "Generated by `neo4d/kit_federation.py`. Party A knows the act for all 16 kinds; party B numbers the kinds "
           "its own way and knows nothing. They exchange only k anchors - (A's code, B's code) for shared faults. "
           f"route4d5 learns the correspondence; B translates A's table. {n:,} trials per row, all 16 codes each.", "",
           "| B's numbering | anchors | k | B knows, right | refused | **wrong** | exact right | exact wrong |",
           "|---|---|---|---|---|---|---|---|"]
    for kind, anchors, k, sh, (er, ef, ew) in rows:
        out.append(f"| {kind} | {anchors} | {k} | {sh['right']:.2%} | {sh['refused']:.2%} | **{sh['wrong']:.3%}** | "
                   f"{float(er):.2%} | {float(ew):.3%} |")
    out += ["", "**What this shows.** When both numberings are affine, five span-aware anchors transfer A's entire table "
            "to B with nothing wrong; random anchors transfer the affine span of what was shared and refuse the rest. "
            "When B's numbering is arbitrary, the same router, from five anchors, answers 5 queries in 13 wrongly; each "
            "validation anchor cuts that about tenfold, exactly as the single-installation case.", "",
            "**What this does not show - it is not zero-knowledge.** The anchors are code pairs in the clear, and the "
            "learned map reveals B's code for every one of A's 16 kinds to B, and to anyone who sees the anchors. "
            "Nothing here hides which faults a party has, proves a fix correct without showing it, or resists a party "
            "that lies about its anchors (a lie is a contradiction or a non-affine map: the router refuses or, from "
            "only five anchors, can be fooled - see the arbitrary rows). A real zero-knowledge exchange needs a "
            "cryptographic protocol, which no integer law here provides.", "",
            f"**Checks failed: {bad}.**"]
    (REPO / "results" / "KIT_FEDERATION.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return int(bad != 0)


if __name__ == "__main__":
    sys.exit(main())
