"""Adversarial "ghost space" queries: neo4d against a guessing heuristic, on the perimeter of the harvested span.

Four harvested examples whose case differences span a rank-3 subspace (a hyperplane of GF(2)^4) - the most
restrictive span four examples can leave open. The ghost queries are the codes OUTSIDE that span: each is one bit
away from a span element, so it looks like the examples, but its answer needs a basis direction the examples do not
contain. Brute force says 8 affine maps survive and they give 8 different answers.

    neo4d       route4d5 (k = 5; the fourth example repeated) - must REFUSE every ghost query
    heuristic   the action of the nearest example, shifted by the same XOR offset (what a pattern-matcher does)

    python -m neo4d.adversarial   -> results/ADVERSARIAL.md
"""
from __future__ import annotations

import random
import sys
from collections import Counter

from neo4d import REPO
from neo4d import edge_cases as E


def nearest_guess(ex, q):
    f, a = min(ex, key=lambda e: (bin(e[0] ^ q).count("1"), e[0]))
    return a ^ (q ^ f)                       # carry the nearest example's offset over - a plausible-looking guess


def main(n=20_000) -> int:
    rng = random.Random(2026)
    route = E.kernels()["route4d5 (k=5)"][0]
    neo, heur, open_answers, dist1 = Counter(), Counter(), Counter(), 0
    total = 0
    for _ in range(n):
        ex, h, span, F1 = E.examples_of_rank(3, 4, rng)
        cand = E.survivors(ex)
        ghosts = [q for q in range(16) if (q ^ F1) not in span]
        q = rng.choice(ghosts)
        total += 1
        dist1 += any(bin((q ^ F1) ^ s).count("1") == 1 for s in span)
        open_answers[len(E.answers(cand, q))] += 1
        got = route(ex, q)
        neo["refused" if got == E.REF else ("right" if got == int(h[q]) else "WRONG")] += 1
        g = nearest_guess(ex, q)
        heur["right" if g == int(h[q]) else "WRONG"] += 1
    pct = lambda c, k: f"{100 * c[k] / total:.1f}%"
    out = ["# Ghost-space queries - neo4d against a guessing heuristic", "",
           f"Generated by `neo4d/adversarial.py`. {total:,} scenarios: four harvested examples spanning a rank-3 subspace, "
           "one query just outside it.", "",
           f"- every ghost query is one bit from a span element: {dist1:,}/{total:,}",
           f"- answers still open per ghost query (brute force over 322,560 maps): {dict(open_answers)}", "",
           "| | right | refused | **wrong** |", "|---|---|---|---|",
           f"| neo4d (route4d5) | {pct(neo, 'right')} | {pct(neo, 'refused')} | **{pct(neo, 'WRONG')}** |",
           f"| nearest-example heuristic | {pct(heur, 'right')} | 0.0% | **{pct(heur, 'WRONG')}** |", "",
           "With 8 answers equally open, any guess is right 1 time in 8 at best: the heuristic's right-rate is the price "
           "of guessing, not bad luck. neo4d's refusal is not a probability - the Determined Test fails, so it never "
           "answers."]
    (REPO / "results" / "ADVERSARIAL.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return int(neo["WRONG"] != 0 or neo["right"] != 0)


if __name__ == "__main__":
    sys.exit(main())
