"""The 4D router on fluid-router's real corpus - fast, symbolic, nothing executed but the decision.

fluid-router's benchmark: 40 bugs injected into five libraries it never saw (humanize, inflection, natsort, parse,
wcwidth); the 33 their own suites catch are the corpus. Its router's claim was measured here: "432/432 decisions
across 16 renumberings, against 27/432 for the frozen table".

A DECISION is one (bug, observed fault kind) where that kind's own act restores the original line byte-for-byte -
17 of them, the 17 byte-exact repairs of fluid-router's benchmark. (An observed kind whose act does not restore the
line is the observer's miss, not the router's; no law can be right there.)
A RENUMBERING relabels the act codes (the act implementations move with their codes); the correct answer moves too.
Three laws decide, each given worked examples under the same renumbering:

    frozen   the original kind -> act table, ignoring the renumbering            (no generalisation)
    ring     fluid-router, verbatim: one worked example (kind 0 -> its act)      (static fluidnet)
    route4d  your affine GF(2)^4 law: three worked examples, the other kinds     (4D)

Two numberings of the same vocabulary are tested: fluidfix's as shipped (act = kind + 5) and a 4D-native one
(act = kind XOR 5) - the corpus fixes which act repairs which fault, never what the codes are.

    python3 corpus4d.py   -> results/CORPUS4D.md
"""
from __future__ import annotations

import ctypes
import json
import random
import subprocess
import sys
from collections import Counter
from pathlib import Path

from neo4d import generalize as G

from neo4d import REPO as ROOT, KERNELS, BUILD
FR = ROOT / "bench" / "fluid-router"
sys.path.insert(0, str(FR))
sys.path.insert(0, str(FR / "examples"))
from fluid_router import route as ring_route          # noqa: E402  the router, verbatim
from kdebug import WORKED_EXAMPLE, apply_act, observe  # noqa: E402

SO = BUILD / "route4d.so"
subprocess.run(["cc", "-O2", "-shared", "-fPIC", "-fwrapv", "-o", str(SO), str(KERNELS / "router4d.c")], check=True)
_r4 = ctypes.CDLL(str(SO)).route4d
_r4.argtypes, _r4.restype = [ctypes.c_int32], ctypes.c_int32
REFUSE = -1


def route4d(examples, q):
    x = 0
    for i, (f, a) in enumerate(examples):
        x |= f << (8 * i) | a << (8 * i + 4)
    v = _r4(x | q << 24) & 31
    return v if v < 16 else REFUSE


def decisions():
    bugs = json.load(open(FR / "benchmark/bugs.json"))
    valid = json.load(open(FR / "benchmark/valid.json"))
    out = []
    for b, ok in zip(bugs, valid):
        if not ok:
            continue
        for k in observe(b["mutated"]):
            act = ring_route(WORKED_EXAMPLE[0], WORKED_EXAMPLE[1], k)     # the act this kind is numbered to
            if apply_act(b["mutated"], act) == b["orig"]:                  # ...and it restores the line
                out.append((b["lib"], b["op"], k, [act]))
    return out


def score(decs, vocab, family, rng, sample=None):
    """vocab: kind -> act under the base numbering. family: array of relabellings of act codes."""
    H = family if sample is None or len(family) <= sample else family[rng.sample(range(len(family)), sample)]
    kinds = sorted(vocab)
    tally = {k: Counter() for k in ("frozen", "ring", "route4d")}
    for g in H:
        for _lib, _op, k, right in decs:
            want = {int(g[a]) for a in right if a in vocab.values()} or {int(g[a]) for a in right}
            # frozen: the old table, blind to the renumbering
            tally["frozen"]["right" if vocab[k] in want else "wrong"] += 1
            # ring: one worked example, kind 0 -> its act, renumbered
            r = ring_route(WORKED_EXAMPLE[0], int(g[vocab[WORKED_EXAMPLE[0]]]), k)
            tally["ring"]["right" if r in want else "wrong"] += 1
            # route4d: three worked examples, the other kinds of the vocabulary, renumbered
            ex = [(f, int(g[vocab[f]])) for f in kinds if f != k]
            assert len(ex) == 3, ex
            r = route4d(ex, k)
            tally["route4d"]["refused" if r == REFUSE else ("right" if r in want else "wrong")] += 1
    return tally


def main() -> int:
    rng = random.Random(2026)
    decs = decisions()
    # the dictionary: kdebug's four acts, kinds 0..3 (whether or not the corpus happens to hit each kind)
    shipped = {k: ring_route(WORKED_EXAMPLE[0], WORKED_EXAMPLE[1], k) for k in range(4)}
    native = {k: k ^ 5 for k in shipped}
    # the act implementations follow their codes: under the native numbering, code k^5 runs what code k+5 ran
    fams = {"ring (16)": (G.ring16(), None), "XOR (16)": (G.xor16(), None),
            "8-cell symmetries (384)": (G.cube16(), None), "affine (3,000 of 322,560)": (G.affine16(), 3000)}
    out = ["# The 4D router on fluid-router's real corpus", "",
           f"Generated by `corpus4d.py`. {len(decs)} decisions from the 33 real bugs fluid-router's benchmark keeps "
           f"(five unseen libraries, injected by a seeded mutation set, caught by their own suites); kinds observed: "
           f"{dict(Counter(d[2] for d in decs))}. Every renumbering of the act codes in each family; right / refused / "
           "**wrong**, as % of decisions.", ""]
    for label, vocab in (("as shipped: act = kind + 5 (a ring numbering)", shipped),
                         ("4D-native: act = kind XOR 5", native)):
        # translate the corpus's correct acts into this numbering
        conv = {shipped[k]: vocab[k] for k in shipped}
        d2 = [(l, o, k, [conv.get(a, a) for a in r]) for l, o, k, r in decs]
        out += [f"## Numbering {label}", "", f"vocabulary: {vocab}", "",
                "| renumbering family | frozen table | ring router (static fluidnet), 1 example | route4d (4D), 3 examples |",
                "|---|---|---|---|"]
        for fname, (H, smp) in fams.items():
            t = score(d2, vocab, H, rng, smp)
            cell = lambda c: (f"{100*c['right']/sum(c.values()):.0f} / {100*c['refused']/sum(c.values()):.0f} / "
                              f"**{100*c['wrong']/sum(c.values()):.0f}**")
            out.append(f"| {fname} | {cell(t['frozen'])} | {cell(t['ring'])} | {cell(t['route4d'])} |")
            n = sum(t["ring"].values())
            print(f"  {label[:22]:22} {fname:26} ring right {t['ring']['right']}/{n}  route4d right "
                  f"{t['route4d']['right']} refused {t['route4d']['refused']} wrong {t['route4d']['wrong']}", flush=True)
        out.append("")
    (ROOT / "results/CORPUS4D.md").write_text("\n".join(out) + "\n")
    print("\n" + "\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
