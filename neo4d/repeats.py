"""How well does neo4d handle repeats? Every fix in the stream is classed by what came before it:

    exact repeat         the same literal edit appeared in an earlier bug              - memory
    generalised repeat   a new literal edit, but its relation appeared in an earlier bug - generalisation
    novel                neither had appeared                                           - new knowledge needed

and scored as the swarm meets it (before learning from it), with the RELATE v2 law deciding every neuron over
literal edits and relations together (neo4d/relate_live.py). A miss is explained by the strength its own neurons
had at that moment: unknown, primed (seen, not yet trusted), active but the generation missed, or costly.

    python -m neo4d.repeats   -> results/REPEATS.md
"""
from __future__ import annotations

import statistics
import sys
from collections import Counter, defaultdict

from neo4d import KERNELS, REPO
from neo4d import relate_live as RL


def run(d, seed, law):
    N = RL.neurons(d, ("rel", "lit"))
    fan = {k: statistics.mean([n for n, _ in v[0] if n] or [0]) for k, v in N.items()}
    cheap = {k: fan[k] <= RL.CHEAP[0] and N[k][1] <= RL.CHEAP[1] for k in N}
    costly = {k: fan[k] > RL.COSTLY[0] or N[k][1] > RL.COSTLY[1] for k in N}
    level, nets, fires, good = defaultdict(int), defaultdict(set), defaultdict(int), defaultdict(int)
    seen_lit, seen_rel = set(), set()
    out = []
    for bug in RL.stream(d, seed):
        before = dict(level)
        act = [k for k, v in before.items() if v >= 2]
        for i in bug:
            r = d["rows"][i]
            cls = "exact repeat" if r["lit"] in seen_lit else ("generalised repeat" if r["rel"] in seen_rel else "novel")
            hit = any(N[k][0][i][1] for k in act)
            own = [k for k in (("lit", r["lit"]), ("rel", r["rel"])) if k in N]
            lv = max((before.get(k, 0) for k in own), default=0)
            if hit:
                why = "covered"
            elif any(costly[k] for k in own) and lv <= 1:
                why = "its pattern is costly - never used"
            elif lv == 0:
                why = "its pattern was unknown" if cls == "novel" else "its pattern cannot generate (not representable)"
            elif lv == 1:
                why = "its pattern was primed - seen, not yet trusted"
            else:
                why = "active, but generation missed it"
            out.append((cls, why, hit))
        for i in bug:
            r = d["rows"][i]
            own = {k for k in (("rel", r["rel"]), ("lit", r["lit"])) if k in N}
            touch = {k for k, v in before.items() if v >= 1 and N[k][0][i][0]} | own
            for k in touch:
                L = level[k]
                n_c, h = N[k][0][i]
                if before.get(k, 0) >= 2 and n_c:
                    fires[k] += 1
                    good[k] += h
                FIRE = int(k in own)
                NEWNET = int(FIRE and r["proj"] not in nets[k])
                PRED = int(before.get(k, 0) >= 1 and h)
                BAR = int(L >= 1 and fires[k] >= RL.BARREN_FIRES and good[k] / fires[k] < RL.BARREN_YIELD)
                x = L | FIRE << 2 | NEWNET << 3 | PRED << 4 | int(cheap[k]) << 5 | int(costly[k]) << 6 | BAR << 7
                level[k] = law(x) & 3
                if FIRE:
                    nets[k].add(r["proj"])
            seen_lit.add(r["lit"])
            seen_rel.add(r["rel"])
    return out


def table(rows):
    by = defaultdict(list)
    for cls, why, hit in rows:
        by[cls].append((why, hit))
    lines = ["| fix | share of fixes | **covered** | why the rest were missed |", "|---|---|---|---|"]
    for cls in ("exact repeat", "generalised repeat", "novel"):
        v = by[cls]
        if not v:
            continue
        miss = Counter(w for w, h in v if not h)
        reasons = "; ".join(f"{w} {c / len(v):.0%}" for w, c in miss.most_common())
        lines.append(f"| {cls} | {len(v) / len(rows):.0%} | **{sum(h for _, h in v) / len(v):.0%}** | {reasons or '-'} |")
    return lines


def main() -> int:
    law = RL.load_law(str(KERNELS / "relate_v2.c"))
    bugs = [row for s in RL.SEEDS for row in run(RL.prep(), s, law)]
    click = run(RL.prep_click(), 0, law)
    out = ["# How well does it handle repeats?", "",
           "Generated by `neo4d/repeats.py`. Each fix is classed by what came before it and scored as the swarm meets it "
           "(RELATE v2 deciding, literal edits and relations as neurons). Covered: an active neuron generates the real "
           "fixed line exactly.", "",
           f"## Real bugs, 49 projects ({len(RL.SEEDS)} orders of the same bugs pooled)", ""]
    out += table(bugs)
    out += ["", "## click's own history, in commit order", ""]
    out += table(click)
    out += ["", "A pattern is used only once the law trusts it: the first sighting primes it, and a cheap pattern "
            "becomes active at once, a mid-cost one after it predicts a fix. A costly one is never used."]
    (REPO / "results" / "REPEATS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
