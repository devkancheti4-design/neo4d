"""Kit test 1 - beyond affine: bigger spaces, projective maps, homology. Exact math, checked by enumeration.

    a  GF(2)^n for n = 4, 5, 6 (16, 32, 64 kinds): the affine group's size, the examples that pin a relabelling (n + 1),
       the bits a word must carry for them (k * 2n + n), and the exact chance k random distinct cases pin it - a
       closed form by Moebius inversion over the subspace lattice, checked by enumeration where it can be.
    b  projective maps over GF(2): PGL(n, 2) acting on the points of PG(n-1, 2) - do they add any relabelling the
       linear group does not already have?
    c  homology of control flow: the cycle rank (first Betti number) of each QuixBugs program's control-flow graph,
       buggy against correct - can it point at missing logic?

    python -m neo4d.kit_scaling   -> results/KIT_SCALING.md
"""
from __future__ import annotations

import ast
import itertools
import math
import sys
from fractions import Fraction as Fr

from neo4d import REPO


def gl_order(n):
    return math.prod(2 ** n - 2 ** i for i in range(n))


def gauss_binom(n, j):
    num = math.prod(2 ** (n - i) - 1 for i in range(j))
    den = math.prod(2 ** (i + 1) - 1 for i in range(j))
    return num // den


def falling(a, m):
    return math.prod(a - i for i in range(m)) if m <= a else 0


def p_pin(n, k):
    """k random distinct points of GF(2)^n affinely span it: the k-1 differences from the first are distinct nonzero
    vectors spanning GF(2)^n. Count spanning tuples by Moebius inversion over the subspace lattice."""
    m = k - 1
    span = sum(gauss_binom(n, j) * (-1) ** (n - j) * 2 ** ((n - j) * (n - j - 1) // 2) * falling(2 ** j - 1, m)
               for j in range(n + 1))
    return Fr(span, falling(2 ** n - 1, m))


def p_pin_enum(n, k):
    pts = range(2 ** n)

    def rank(vs):
        basis = []
        for v in vs:
            for b in basis:
                v = min(v, v ^ b)
            if v:
                basis.append(v)
        return len(basis)
    good = sum(rank([s ^ S[0] for s in S[1:]]) == n for S in itertools.combinations(pts, k))
    return Fr(good, math.comb(2 ** n, k))


def projective_check(n=4):
    """Every invertible matrix acts on the nonzero vectors (= the points of PG(n-1, 2), since the only scalar is 1).
    Count the distinct permutations of the points it induces."""
    perms = set()
    pts = list(range(1, 2 ** n))
    for cols in itertools.product(range(1, 2 ** n), repeat=n):
        img = []
        for x in pts:
            v = 0
            for i in range(n):
                if x >> i & 1:
                    v ^= cols[i]
            img.append(v)
        if len(set(img)) == len(pts) and 0 not in img:
            perms.add(tuple(img))
    return len(perms)


def cycle_rank(src):
    """McCabe's cyclomatic number = the first Betti number of the control-flow graph (+1 per decision point)."""
    tree = ast.parse(src)
    d = 0
    for n in ast.walk(tree):
        if isinstance(n, (ast.If, ast.For, ast.While, ast.IfExp, ast.ExceptHandler, ast.With, ast.Assert,
                          ast.comprehension)):
            d += 1
        elif isinstance(n, ast.BoolOp):
            d += len(n.values) - 1
    return d + 1


def main() -> int:
    out = ["# Kit 1 - beyond affine", "", "Generated by `neo4d/kit_scaling.py`.", "",
           "## a. Bigger spaces: GF(2)^n", "",
           "| n | kinds | affine relabellings | examples to pin one | bits a word must carry | fits int64? | 6 random cases pin it | 7 | 8 |",
           "|---|---|---|---|---|---|---|---|---|"]
    bad = 0
    for n in (4, 5, 6):
        size = 2 ** n * gl_order(n)
        k = n + 1
        bits = k * 2 * n + n
        cells = []
        for kk in (6, 7, 8):
            p = p_pin(n, kk)
            cells.append(f"{p} = {float(p):.4f}" if p.denominator < 10 ** 7 else f"{float(p):.4f}")
        out.append(f"| {n} | {2 ** n} | {size:,} | **{k}** | **{bits}** | {'yes' if bits <= 64 else '**no**'} | "
                   + " | ".join(cells) + " |")
    checks = []
    for n, k in ((4, 5), (4, 6), (4, 7), (5, 6), (5, 7)):
        f, e = p_pin(n, k), p_pin_enum(n, k)
        checks.append((n, k, f, e))
        bad += f != e
    out += ["", "The closed form against full enumeration of every k-subset:", "",
            "| n | k | closed form | enumeration | |", "|---|---|---|---|---|"]
    for n, k, f, e in checks:
        out.append(f"| {n} | {k} | {f} | {e} | {'OK' if f == e else 'MISMATCH'} |")
    out += ["", "**GF(2)^5 needs a new router and a wider word**: six examples of 10 bits plus a 5-bit query is 65 bits - "
            "one more than an int64. GF(2)^6 needs 90. A k = 6 router for 32 kinds would read two words (or an "
            "__int128).", ""]
    pg = projective_check()
    out += ["## b. Projective maps over GF(2)", "",
            f"PGL(4, 2) acting on the 15 points of PG(3, 2) induces **{pg:,}** distinct relabellings; GL(4, 2) has "
            f"**{gl_order(4):,}**. Over GF(2) the only scalar is 1, so projective and linear maps are the same group: "
            "projective geometry adds no relabelling the affine router does not already have.", ""]
    bad += pg != gl_order(4)
    qb = REPO / "bench" / "QuixBugs"
    rows, changed, up, down = [], 0, 0, 0
    for p in sorted((qb / "python_testcases").glob("test_*.py")):
        name = p.stem[5:]
        b = (qb / "python_programs" / f"{name}.py").read_text()
        c = (qb / "correct_python_programs" / f"{name}.py").read_text()
        rb, rc = cycle_rank(b), cycle_rank(c)
        changed += rb != rc
        up += rc > rb
        down += rc < rb
        rows.append((name, rb, rc))
    out += ["## c. Homology of control flow (QuixBugs, 40 programs)", "",
            f"The fix changes the control-flow graph's cycle rank in **{changed} of 40** programs (adds a cycle in {up} "
            f"- logic that was missing - removes one in {down}); in the other {40 - changed} the bug is inside "
            "unchanged control flow.", "",
            "Cycle rank is a single number of the BUGGY program; without the correct program there is nothing to "
            "compare it with, so it cannot say that logic is missing, let alone where. Detecting missing logic needs "
            "a reference - a test that fails (fluidnet's omission law) - not topology alone.", "",
            f"**Checks failed: {bad}.**"]
    (REPO / "results" / "KIT_SCALING.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return int(bad != 0)


if __name__ == "__main__":
    sys.exit(main())
