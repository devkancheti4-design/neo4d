"""Write results/GREEN.md from the metered fluidnet runs and the agent's recorded runs on the same bugs.

fluidnet  measured here by green.py: CPU-seconds of every process it ran (exact), and whole-machine energy from
          the Mac's power telemetry (coarse - it updates every ~30-60 s and the machine had a browser busy, so it is
          a cross-check, with its uncertainty stated). CPU energy = CPU-seconds x the per-core power calibrated by
          calibrate_core_w() on this machine.
agent     recorded by fluidnet's own click race (race_agent.jsonl): seconds and tokens per bug, 10/10 byte-exact.
          Its energy is NOT measured anywhere - it is priced from published estimates, as a range:
            high  Epoch AI's model for GPT-4o-class serving on H100 (10% utilisation, no caching), fitted to its
                  two published points: 10k input tokens ~ 2.5 Wh, 100k ~ 40 Wh  ->  E(n) = a n + b n^2
            mid   the same per-token rate a, without the long-context term
            low   only the tokens beyond the runtime's fixed overhead (43,763 tokens for an empty call, measured by
                  the race), as if that overhead were cached and free
"""
from __future__ import annotations

import json
import statistics as st
from pathlib import Path

from neo4d import REPO as ROOT, KERNELS
RACE = ROOT / "bench" / "fluidnet" / "docs" / "results" / "2026-09-25" / "data"
OVERHEAD = 43_763                      # tokens of an empty call to the race's agent runtime ("reply OK")

# Epoch AI, "How much energy does ChatGPT use?": 10k in + 500 out ~ 2.5 Wh; 100k in + 500 out ~ 40 Wh
B = (40 - 10 * 2.5) / (1e10 - 10 * 1e8)          # Wh per token^2
A = (2.5 - 1e8 * B) / 1e4                         # Wh per token
WH = 3600.0


def agent_joules(tokens: int) -> dict:
    return {"high": (A * tokens + B * tokens ** 2) * WH,
            "mid": A * tokens * WH,
            "low": A * max(0, tokens - OVERHEAD) * WH}


def main() -> int:
    runs = {r["id"]: r for r in (json.loads(l) for l in open(ROOT / "results/green_runs.jsonl") if l.strip())}
    agent = {r["id"]: r for r in (json.loads(l) for l in open(RACE / "race_agent.jsonl"))}
    cal = json.load(open(ROOT / "results/green_core_w.json")) if (ROOT / "results/green_core_w.json").exists() else None
    core_w = cal["w_per_busy_core"] if cal else None
    rows, tot = [], {"fn_cpu": 0, "fn_sys": 0, "fn_cpuJ": 0, "ag_low": 0, "ag_mid": 0, "ag_high": 0,
                     "fn_ok": 0, "ag_ok": 0, "fn_secs": [], "ag_secs": [], "loc": 0, "rep": 0}
    for bid, r in runs.items():
        a = agent.get(bid, {})
        tok = int(a.get("tokens", 0) or 0)
        aj = agent_joules(tok)
        ok = r["exact"] and r["suite_green"]
        cpuJ = r["cpu_s"] * core_w if core_w else None
        loc = sum(float(s.split("s ")[0].split()[-1]) for s in r["stages"] if s.startswith("locate"))
        rows.append((bid, r["at"], r["how_known"], ok, r["secs"], r["cpu_s"], cpuJ, r["joules_total"],
                     a.get("secs"), tok, aj, a.get("exact"), loc))
        tot["fn_cpu"] += r["cpu_s"]; tot["fn_sys"] += r["joules_total"]; tot["fn_cpuJ"] += cpuJ or 0
        for k in ("low", "mid", "high"):
            tot[f"ag_{k}"] += aj[k]
        tot["fn_ok"] += ok; tot["ag_ok"] += bool(a.get("exact"))
        tot["fn_secs"].append(r["secs"]); tot["ag_secs"].append(a.get("secs", 0))
        tot["loc"] += loc; tot["rep"] += r["secs"] - loc
    n = len(rows)
    kj = lambda j: f"{j / 1000:.1f}"
    out = ["# Green benchmark - energy per certified repair, fluidnet vs an AI agent, same real bugs", "",
           f"fluidnet's own click race (click 06b2a67, 2,240 tests): {n} real single-token bugs rebuilt from the race "
           "logs. **fluidnet is measured here** (`green.py`, this Mac, an Apple M4 Pro); **the agent is the race's "
           "recorded run** (seconds and tokens per bug) with its energy **priced from published estimates**, never "
           "measured. Generated by `green_report.py`.", ""]
    if cal:
        out.append(f"CPU energy uses **{core_w:.2f} W per busy core**, calibrated on this machine "
                   f"({cal['note']}).")
        out.append("")
    out += ["| bug | how it was rebuilt | fluidnet: repaired, certified | fluidnet s | fluidnet CPU s | fluidnet CPU kJ | "
            "fluidnet whole-machine kJ | agent s | agent tokens | agent kJ (low / mid / high) |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for bid, at, how, ok, secs, cpu, cpuJ, sysJ, asecs, tok, aj, aok, loc in rows:
        out.append(f"| {at} | {how} | {'yes' if ok else 'NO'} | {secs:.0f} | {cpu:.0f} | "
                   f"{kj(cpuJ) if cpuJ is not None else '-'} | {kj(sysJ)} | {asecs} | {tok:,} | "
                   f"{kj(aj['low'])} / {kj(aj['mid'])} / {kj(aj['high'])} |")
    fn_per = tot["fn_cpuJ"] / max(1, tot["fn_ok"]) if core_w else None
    out += ["", "## Per certified repair", "",
            "| | fluidnet (measured) | AI agent (recorded time and tokens; energy estimated) |", "|---|---|---|",
            f"| correct | {tot['fn_ok']}/{n}, each certified by the full suite | {tot['ag_ok']}/{n} byte-exact, nothing checked |",
            f"| median time | {st.median(tot['fn_secs']):.0f} s | {st.median(tot['ag_secs']):.0f} s |",
            f"| tokens | 0 | {sum(r[9] for r in rows):,} |",
            f"| energy per correct repair | {kj(fn_per) + ' kJ CPU' if fn_per else '-'}, "
            f"{kj(tot['fn_sys'] / max(1, tot['fn_ok']))} kJ whole machine | "
            f"{kj(tot['ag_low'] / max(1, tot['ag_ok']))} / {kj(tot['ag_mid'] / max(1, tot['ag_ok']))} / "
            f"{kj(tot['ag_high'] / max(1, tot['ag_ok']))} kJ (low / mid / high) |",
            "", "## Where fluidnet's time goes", "",
            f"Locating the line (buggy's mutation testing): **{100 * tot['loc'] / max(1, tot['loc'] + tot['rep']):.0f}%** "
            f"of fluidnet's time. The taught repair and its certification: the rest. The laws themselves: microseconds. "
            "Once the line is known, a taught class repairs at the speed of the project's own suite.", "",
            "## What this does not show", "",
            "- The agent's energy is an estimate from published serving models, spanning more than 10x; nobody measured "
            "the agent's watts. fluidnet's is measured, on a laptop.",
            "- The whole-machine figure includes everything else the Mac was doing (a browser was busy throughout); "
            "the CPU figure counts only fluidnet's processes.",
            "- This run uses fluidfix 0.16.0 from PyPI, which lacks `repair --focus`: fluidnet's uniqueness check "
            "(is this the ONLY passing fix at its line?) was skipped where the race's final build ran it.",
            "- Bug 5292 was rebuilt from its fault kind, not from a logged line; 4175 is left out - its planted line "
            "was not recorded.",
            "- The agent also ran click's suite itself; that energy is not in its column.",
            "", "Sources: Epoch AI, *How much energy does ChatGPT use?* (https://epoch.ai/gradient-updates/how-much-"
            "energy-does-chatgpt-use); fluidnet's race data, docs/results/2026-09-25."]
    (ROOT / "results/GREEN.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
