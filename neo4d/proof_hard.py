"""The proof of results/PROOF_GROWS.md on harder data: does it still mutate unseen code, and does its knowledge still
grow? Each setting is taught from scratch in that setting, files split in half (taught / never seen), the RELATE v2
law deciding, anchored relations, the domain's junk budget.

    C              Homebrew packages (ncurses, tcl, ffmpeg, libtool, git ...)
    C++            libc++ headers - templates everywhere
    Java           QuixBugs (small: a few hundred lines to teach from)
    hard, Python   the teacher adds argument swaps, subscript off-by-one, call deletion
    hard, C        ... and ++ <-> --
    noisy teacher  Python, 10% of lessons replaced by random wrong edits

    python -m neo4d.proof_hard   -> results/PROOF_HARD.md
"""
from __future__ import annotations

import random
import sys

from neo4d import KERNELS, REPO
from neo4d import domain_hard as H
from neo4d import domain_mutation as D
from neo4d import relate_live as RL
from neo4d.proof_grows import show

KS = (10, 30, 100, 300, 1000, 3000, 10000)


def examples(dom, act, test, n=2, seed=7):
    idx = D.Index(act)
    pool = [i for i in test if 2 <= len(dom.lines[i]["refs"]) <= 6]
    out = []
    for i in random.Random(seed).sample(pool, min(n, len(pool))):
        x = dom.lines[i]
        cands = set()
        for k in idx.on(x):
            cands |= dom.gen(k, i)
        real = set(x["refs"])
        out.append(f"`{show(x['a'])}`")
        out.append("")
        for m in sorted(cands, key=show)[:6]:
            out.append(f"- {'✓' if m in real else '✗'} `{show(m)}`")
        if len(cands) > 6:
            out.append(f"- ... {len(cands) - 6} more")
        out.append(f"- teacher's mutants it did not generate: {len(real - cands)}")
        out.append("")
    return out


def curve(dom, tr, te, law, noise=0.0, ks=KS):
    order = random.Random(0).sample(tr, min(len(tr), max(ks)))
    ks = sorted({k for k in ks if k <= len(order)} | {len(order)})
    rows, act = [], set()
    for k in ks:
        act = D.teach(dom, order[:k], law, ("ctx",), costly_t=D.JUNK, noise=noise, noise_seed=0)
        rows.append((k, len(act), D.evaluate(dom, act, te)))
    return rows, act


def main() -> int:
    law = RL.load_law(str(KERNELS / "relate_v2.c"))
    C = H.corpora()
    base = D.Domain(raw=C["c"] + C["cpp"] + C["java"] + C["lib"])
    hard = D.Domain(raw=C["lib"] + C["c"], hard=True)
    SB, SH = H.sets_of(base), H.sets_of(hard)
    settings = [("C (Homebrew packages)", base, SB["c"], 0.0), ("C++ (libc++)", base, SB["cpp"], 0.0),
                ("Java (QuixBugs)", base, SB["java"], 0.0), ("harder operators, Python", hard, SH["py"], 0.0),
                ("harder operators, C", hard, SH["c"], 0.0), ("noisy teacher, 10% wrong lessons", base, SB["py"], 0.1)]
    out = ["# The proof on harder data", "",
           "Generated by `neo4d/proof_hard.py`. Each setting is taught from scratch in that setting, its files split in "
           "half: taught, and never seen. RELATE v2 decides every pattern. Coverage: the share of the unseen files' real "
           "mutants it generates. Precision: the share of what it generates that is a real mutant.", ""]
    summary = []
    for name, dom, idx, noise in settings:
        tr, te = H.halves(dom, idx, 0)
        te = H.sample(te, H.N_EVAL, 0)
        ks = (100, 1000, 10000) if noise else KS
        rows, act = curve(dom, tr, te, law, noise, ks)
        out += [f"## {name}", "",
                f"{len(tr):,} lines to teach from, {len(te):,} unseen lines tested.", "",
                "| lines taught | active patterns | coverage of unseen files | precision |", "|---|---|---|---|"]
        for k, n_act, e in rows:
            out.append(f"| {k:,} | {n_act:,} | **{e['cov']:.1%}** | {e['prec']:.1%} |")
        last = rows[-1][2]
        if "harder" in name:
            ops = sorted(last["n_op"], key=lambda o: -last["n_op"][o])
            out += ["", "By operator at the most teaching: " + ", ".join(f"{o} {last['by_op'][o]:.0%}" for o in ops) + "."]
        out += ["", "Mutants it generated on unseen lines (✓ the teacher makes it too, ✗ it does not):", ""]
        out += examples(dom, act, te)
        summary.append((name, rows[0], rows[-1]))
        print(f"  {name} done", flush=True)
    out += ["## Summary", "", "| setting | taught | coverage | precision | taught | coverage | precision |",
            "|---|---|---|---|---|---|---|"]
    for name, (k0, _, e0), (k1, _, e1) in summary:
        out.append(f"| {name} | {k0:,} | {e0['cov']:.1%} | {e0['prec']:.1%} | {k1:,} | **{e1['cov']:.1%}** | "
                   f"**{e1['prec']:.1%}** |")
    (REPO / "results" / "PROOF_HARD.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
