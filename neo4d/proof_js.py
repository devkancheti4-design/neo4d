"""The proof on JavaScript - does it mutate a JavaScript codebase, and carry what it learns to NEW TOPICS?

THE CODE. Every package of the JavaScript tools installed on this machine (netlify-cli, npm, and the hundreds of
packages they depend on: web servers, HTTP clients, template engines, CLIs, parsers ...). Each package is a TOPIC.
Minified and bundled files are left out; at most 2,000 lines a file and 3,000 a package, so no package dominates.

THE TEACHER. The standard mutation operators in their JavaScript form (neo4d/domain_mutation.py, lang "js"):
comparisons including `===` / `!==`, arithmetic, `&&` / `||`, `true` / `false`, `!`, numbers, `++` / `--`,
`break` / `continue`, `return x;` -> `return null;`.

THE TEST. Half the topics are taught; the other half are never seen - new topics. RELATE v2 decides every pattern.

    A  JavaScript taught from scratch: growth from 10 to 30,000 lines, tested on the new topics
    B  new topics against unseen files of topics it was taught
    C  Python first: taught only Python, then Python plus a little JavaScript
    D  operator by operator, and mutants it generated on new-topic code

    python -m neo4d.proof_js   -> results/PROOF_JS.md
"""
from __future__ import annotations

import random
import sys
from collections import defaultdict
from pathlib import Path

from neo4d import KERNELS, REPO
from neo4d import domain_hard as H
from neo4d import domain_mutation as D
from neo4d import relate_live as RL


def show(m):
    """A token list as JavaScript."""
    js = {"NULL": "null", "NOT": "!", "AND": "&&", "OR": "||", "TRUE": "true", "FALSE": "false"}
    return " ".join(js.get(t, t) for t in m if t != "^").replace("_S_", "$")

ROOT = Path("/opt/homebrew/lib/node_modules")
KS = (10, 30, 100, 300, 1000, 3000, 10000, 30000)
PER_PACKAGE = 3000


def package_of(p):
    parts = p.relative_to(ROOT).parts
    idx = [i for i, x in enumerate(parts) if x == "node_modules"]
    i = idx[-1] + 1 if idx else 0
    return "/".join(parts[i:i + 2]) if parts[i].startswith("@") else parts[i]


def js_corpus(seed=11):
    files = [p for p in ROOT.rglob("*") if p.suffix in (".js", ".mjs", ".cjs") and p.is_file()
             and not p.name.endswith(".min.js") and "dist" not in p.parts and p.stat().st_size < 200_000]
    by = defaultdict(list)
    for p in files:
        by[package_of(p)].append(p)
    out = []
    for pkg in sorted(by):
        lines = H.c_lines(sorted(by[pkg])[:200], lambda q, pkg=pkg: pkg, "js", "js")
        out += lines[:PER_PACKAGE]
    return out


def main() -> int:
    law = RL.load_law(str(KERNELS / "relate_v2.c"))
    js = js_corpus()
    lib = [(f"py:{n}", l, s, "py") for n, l, s in D.corpus()]
    dom = D.Domain(raw=js + lib)
    S = H.sets_of(dom)
    J = S["js"]
    topics = sorted({dom.lines[i]["net"] for i in J})
    rng = random.Random(0)
    rng.shuffle(topics)
    new = set(topics[:len(topics) // 2])
    taught_topics = [i for i in J if dom.lines[i]["net"] not in new]
    # hold out a fifth of the files of the taught topics: seen topics, unseen files
    files = sorted({(dom.lines[i]["net"], dom.lines[i]["scope"][0]) for i in taught_topics})
    held_files = set(random.Random(1).sample(files, len(files) // 5))
    tr = [i for i in taught_topics if (dom.lines[i]["net"], dom.lines[i]["scope"][0]) not in held_files]
    seen_unseen = H.sample([i for i in taught_topics if (dom.lines[i]["net"], dom.lines[i]["scope"][0]) in held_files],
                           H.N_EVAL, 0)
    te = H.sample([i for i in J if dom.lines[i]["net"] in new], H.N_EVAL, 0)
    n_mut = sum(len(dom.lines[i]["refs"]) for i in J)
    order = random.Random(0).sample(tr, min(len(tr), max(KS)))
    out = ["# The proof on JavaScript - a codebase, and new topics", "",
           "Generated by `neo4d/proof_js.py`. The JavaScript of the tools installed on this machine (netlify-cli, npm "
           f"and their dependencies): **{len(J):,} lines in {len(topics)} packages, {n_mut:,} mutants**. Each package is "
           f"a topic. **{len(new)} topics are never taught** - the new topics; the other {len(topics) - len(new)} are "
           "taught (a fifth of their files held back). RELATE v2 decides every pattern; coverage is the share of real "
           "mutants it generates, precision the share of its output that is real.", "",
           "New topics include: " + ", ".join(f"`{t}`" for t in sorted(new)[:24]) + " ...", "",
           "## A. JavaScript taught from scratch - growth, tested on new topics", "",
           "| lines taught | active patterns | coverage of new topics | precision |", "|---|---|---|---|"]
    act = set()
    for k in [k for k in KS if k <= len(order)]:
        act = D.teach(dom, order[:k], law, ("ctx",), costly_t=D.JUNK)
        e = D.evaluate(dom, act, te)
        out.append(f"| {k:,} | {len(act):,} | **{e['cov']:.1%}** | {e['prec']:.1%} |")
        print(f"  taught {k}: coverage {e['cov']:.3f} precision {e['prec']:.3f}", flush=True)
    last_new, last_seen = D.evaluate(dom, act, te), D.evaluate(dom, act, seen_unseen)
    out += ["", "## B. New topics against seen topics", "",
            "| tested on (after the most teaching) | coverage | precision |", "|---|---|---|",
            f"| unseen files of topics it was taught | {last_seen['cov']:.1%} | {last_seen['prec']:.1%} |",
            f"| **topics it never saw** | **{last_new['cov']:.1%}** | **{last_new['prec']:.1%}** |", ""]
    py_order = random.Random(0).sample([i for i in S["py"]], 10000)
    out += ["## C. Python first", "",
            "| taught | coverage of new JavaScript topics | precision |", "|---|---|---|"]
    for label, taught in (("10,000 Python lines, no JavaScript", py_order),
                          ("10,000 Python + 30 JavaScript", py_order + order[:30]),
                          ("10,000 Python + 300 JavaScript", py_order + order[:300]),
                          ("10,000 Python + 3,000 JavaScript", py_order + order[:3000]),
                          ("30 JavaScript alone", order[:30]), ("300 JavaScript alone", order[:300])):
        e = D.evaluate(dom, D.teach(dom, taught, law, ("ctx",), costly_t=D.JUNK), te)
        out.append(f"| {label} | **{e['cov']:.1%}** | {e['prec']:.1%} |")
    print("  python-first done", flush=True)
    ops = sorted(last_new["n_op"], key=lambda o: -last_new["n_op"][o])
    tot = sum(last_new["n_op"].values())
    out += ["", "## D. Operator by operator, on new topics", "",
            "| operator | share of mutants | covered |", "|---|---|---|"]
    for o in ops:
        out.append(f"| {o} | {last_new['n_op'][o] / tot:.1%} | {last_new['by_op'][o]:.0%} |")
    out += ["", "Mutants it generated on new-topic code (✓ the teacher makes it too, ✗ it does not):", ""]
    idx = D.Index(act)
    pool = [i for i in te if 2 <= len(dom.lines[i]["refs"]) <= 6]
    for i in random.Random(5).sample(pool, min(4, len(pool))):
        x = dom.lines[i]
        cands = set()
        for k in idx.on(x):
            cands |= dom.gen(k, i)
        real = set(x["refs"])
        out += [f"**`{show(x['a'])}`**  (topic `{x['net'].split(':', 1)[1]}`)", ""]
        for m in sorted(cands, key=show)[:6]:
            out.append(f"- {'✓' if m in real else '✗'} `{show(m)}`")
        out += [f"- teacher's mutants it did not generate: {len(real - cands)}", ""]
    (REPO / "results" / "PROOF_JS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
