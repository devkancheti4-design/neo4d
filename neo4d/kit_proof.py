"""Kit test 5 - formal verification: route4d5 checked on EVERY input of its reduced space, against an independent
reference (neo4d/kit/exhaust5.c: Gaussian elimination over GF(2), no shared code with the kernel).

The reduced space fixes F1 = A1 = 0 - route4d5 reads them only through XOR differences and a final XOR, so it is
translation-equivariant by construction, and the judge's G4 checks that separately. That leaves 36 bits:
68,719,476,736 words. The count the reference must find determined is also derived in closed form (below), so the
reference is checked too, not only the kernel.

    python -m neo4d.kit_proof              compile, run on every core (about 10 minutes on 12), report
    python -m neo4d.kit_proof --collect    report from the outputs of an earlier run in .build/
"""
from __future__ import annotations

import itertools
import math
import os
import subprocess
import sys

from neo4d import BUILD, KERNELS, PKG, REPO

TOTAL = 1 << 36


def closed_form_determined():
    """Words with F1 = A1 = 0 whose query is determined: over the 4-tuples d of case differences of rank r, the
    consistent action tuples are the injective linear images of span{d} (prod_{i<r} (16 - 2^i)) and the query must lie
    in span{d} (2^r of 16)."""
    def rank(vs):
        basis = []
        for v in vs:
            for b in basis:
                v = min(v, v ^ b)
            if v:
                basis.append(v)
        return len(basis)
    by_rank = [0] * 5
    for d in itertools.product(range(16), repeat=4):
        by_rank[rank(d)] += 1
    return sum(c * math.prod(16 - 2 ** i for i in range(r)) * 2 ** r for r, c in enumerate(by_rank))


def run(slices):
    exe = BUILD / "exhaust5"
    BUILD.mkdir(exist_ok=True)
    subprocess.run(["cc", "-O3", "-march=native", "-o", str(exe), str(PKG / "kit" / "exhaust5.c"),
                    str(KERNELS / "router4d5.c")], check=True)
    for f in BUILD.glob("exhaust5_*.out"):
        f.unlink()
    procs = [subprocess.Popen([str(exe), str(s), str(slices)], stdout=open(BUILD / f"exhaust5_{s}.out", "w"))
             for s in range(slices)]
    for p in procs:
        p.wait()


def main() -> int:
    if "--collect" not in sys.argv:
        run(os.cpu_count() or 8)
    rows = [list(map(int, f.read_text().split())) for f in sorted(BUILD.glob("exhaust5_*.out"))]
    words, bad, det, ref = (sum(r[i] for r in rows) for i in (1, 2, 3, 4))
    want = closed_form_determined()
    fails = int(words != TOTAL) + int(bad != 0) + int(det != want) + int(ref != TOTAL - want)
    out = ["# Kit 5 - route4d5, verified on every input", "",
           "Generated by `neo4d/kit_proof.py`. The kernel against an independent reference (`neo4d/kit/exhaust5.c`: "
           "Gaussian elimination over GF(2)) on every word of its reduced input space - F1 = A1 = 0, which loses "
           "nothing: route4d5 is translation-equivariant by construction and the judge's G4 checks it.", "",
           "| | count |", "|---|---|",
           f"| words checked | **{words:,}** of 2^36 = {TOTAL:,} |",
           f"| kernel differs from the reference | **{bad:,}** |",
           f"| determined (an answer) | {det:,} |",
           f"| refused | {ref:,} |",
           f"| determined, closed form | {want:,} - {'equal' if det == want else 'DIFFERENT'} |", "",
           f"{len(rows)} slices. Every one of the 2^36 reduced words - every five examples, consistent or "
           "contradictory, spanning or degenerate, and every query - gets exactly the answer Gaussian elimination "
           "gives, or the same refusal. The determined count matching its closed form checks the reference itself.", "",
           "With route4d (k = 3: all 1,048,576 reduced words, `judge_router4d.reduced`, 0 violations) and the 8-bit "
           "laws PICK, HARVEST, INDUCE and SHIP, whose judges enumerate all 256 inputs, every authored kernel in "
           "`neo4d/kernels/` has now been checked on its whole input space.", "",
           f"**Checks failed: {fails}.**"]
    (REPO / "results" / "KIT_PROOF.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return int(fails != 0)


if __name__ == "__main__":
    sys.exit(main())
