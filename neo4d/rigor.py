"""Rigour for the paper: ablations, a random control, and coverage-guided search on files of growing size.

    --law          the RELATE v2 law against simpler rules, under a noisy teacher (the mutation domain, 3 seeds):
                   v2; v2 with the BARREN bit ignored; trust at first sight (no law: every pattern used, never weakened)
    --agent        the same rules, and plans without slots, on the 85 agent tasks, from the recorded Sonnet and Haiku work
    --random       deep search on the hard bugs with a RANDOM filter (5 seeds) - the control for Haiku's picks
    --coverage     one bug in files of 1, 4, 16 and 31 functions: search every line, only the lines the failing tests
                   run, or those lines ranked by suspicion (Ochiai) - test runs until the fix, 3 seeds
    --baselines M  the 31 real bugs, every method allowed 10 model calls a bug, 3 seeds, for local models M:
                   sample-and-filter (independent tries, first that passes); self-debugging (the model sees its last
                   program and the first failing test); Reflexion (after a failure the model writes a short reflection,
                   kept for later attempts; a reflection costs a call); the neo4d loop. 95% bootstrap intervals over
                   bugs, and a paired permutation test of neo4d against each

    python -m neo4d.rigor --law --agent --random --coverage   -> results/RIGOR.md
"""
