OUT = REPO / "results" / "RIGOR.md"


def rules():
    v2 = RL.load_law(str(KERNELS / "relate_v2.c"))
    return (("RELATE v2", v2),
            ("v2, the BARREN bit ignored", lambda x: v2(x & 0x7F)),
            ("trust at first sight (no law)", lambda x: 2 if (x >> 2) & 1 or (x & 3) >= 2 else x & 3))


def section(title, lines):
    import fcntl
    with open(OUT.with_suffix(".lock"), "w") as lock:   # the tests run as parallel processes: one writer at a time
        fcntl.flock(lock, fcntl.LOCK_EX)
        _section(title, lines)


def _section(title, lines):
    parts = OUT.read_text().rstrip("\n").split("\n## ") if OUT.exists() else [
        "# Rigour: ablations, a random control, coverage-guided search\n\nGenerated by `neo4d/rigor.py`."]
    parts = [p for p in parts if not p.startswith(title)] + ["\n".join([title, ""] + lines)]
    OUT.write_text("\n\n## ".join(p.strip("\n") for p in parts) + "\n")
    print("\n".join(["## " + title, ""] + lines), flush=True)


# ---------------------------------------------------------------------------------------- the law, noisy teacher

def law_ablation():
    C = H.corpora()
    base = D.Domain(raw=C["lib"])
    S = H.sets_of(base)
    res = defaultdict(list)
    for seed in H.SEEDS:
        nets = sorted({base.lines[i]["net"] for i in S["py"]})
        random.Random(1000 + seed).shuffle(nets)
        held = set(nets[:len(nets) // 4])
        train = [i for i in S["py"] if base.lines[i]["net"] not in held]
        test = H.sample([i for i in S["py"] if base.lines[i]["net"] in held], H.N_EVAL, seed)
        taught = random.Random(seed).sample(train, 10000)
        for nz in (0.0, 0.1, 0.3):
            for name, law in rules():
                act = D.teach(base, taught, law, ("ctx",), costly_t=D.JUNK, noise=nz, noise_seed=seed)
                e = D.evaluate(base, act, test)
                res[(name, nz)].append((e["cov"], e["prec"], len(act)))
        print(f"  law ablation seed {seed} done", flush=True)
    out = ["The mutation domain, 10,000 lessons, evaluated on held-out modules; mean over 3 seeds (the range in "
           "brackets). A wrong lesson teaches a mutant that is not one.", "",
           "| rule | wrong lessons | coverage | **precision** | active patterns |", "|---|---|---|---|---|"]
    for nz in (0.0, 0.1, 0.3):
        for name, _ in rules():
            r = res[(name, nz)]
            pr = [x[1] for x in r]
            out.append(f"| {name} | {nz:.0%} | {statistics.mean(x[0] for x in r):.1%} | **{statistics.mean(pr):.1%}** "
                       f"({min(pr):.1%}-{max(pr):.1%}) | {statistics.mean(x[2] for x in r):,.0f} |")
    section("Ablation: the law, under a noisy teacher", out)


# ------------------------------------------------------------------------------------- the law and slots, agent work

def agent_ablation():
    meta = json.loads((A.BUILD / "agent_meta.json").read_text())
    A.build_project()
    tasks = A.make_tasks(meta)
    out = ["The 85 agent tasks, replayed from the recorded work of Claude Sonnet and Claude Haiku (as in LOCAL_AGENT.md): "
           "neo4d runs its trusted plans that need no model call; the model's own work counts for every other task. "
           "Every replay is checked, so accuracy cannot fall; what changes is how much work neo4d takes, and how many "
           "replays it wastes.", "",
           "| model | rule | plans | accepted | tasks needing the model | failed replays |", "|---|---|---|---|---|---|"]
    orig = (A.skeleton, A.slots_of)
    for run in ("sonnet", "haiku"):
        tr = {t["id"]: json.loads((REPO / "results" / "data" / "agent_runs" / run / f"{t['id']}.json").read_text())
              for t in tasks}
        ok = {}
        for t in tasks:
            sb = A.Sandbox(t)
            for a, _, _ in tr[t["id"]]:
                if a.get("tool") not in ("invalid", "done"):
                    sb.act(a)
            ok[t["id"]] = A.accepted(t, sb)
            sb.close()
        for slots in (True, False):
            for name, law in (rules() if slots else rules()[:1]):
                if not slots:
                    A.skeleton, A.slots_of = (lambda text: text), (lambda text: [])
                try:
                    brain, stats, need, wasted, good = A.Brain(law), defaultdict(int), 0, 0, 0
                    for t in tasks:
                        tried, shadow, how, keep = {}, {}, None, None
                        for plan in [p for p in brain.ranked(t["text"], 2, 3) if '"write": true' not in "".join(p)][:2]:
                            trace, a = A.replay(plan, t, None, stats)
                            tried[plan] = a
                            wasted += not a
                            if a:
                                how, keep = "neo4d", trace
                                break
                        if how is None and ok[t["id"]]:
                            how, keep = "model", tr[t["id"]]
                        for plan in [p for p in brain.ranked(t["text"], 1, 1)
                                     if p not in tried and '"write": true' not in "".join(p)][:2]:
                            shadow[plan] = A.replay(plan, t, None, stats)[1]
                        brain.learn(t, keep, tried, shadow)
                        need += how != "neo4d"
                        good += how is not None
                finally:
                    A.skeleton, A.slots_of = orig
                label = name if slots else "RELATE v2, plans WITHOUT slots (names kept literal)"
                out.append(f"| {run} | {label} | {'with slots' if slots else 'literal'} | {good}/{len(tasks)} | "
                           f"**{need}** | {wasted} |")
                print(f"  agent ablation {run} {label}: need {need}, wasted {wasted}", flush=True)
    section("Ablation: the law and the slots, on agent work", out)


# --------------------------------------------------------------------------------- a random filter for deep search

def random_search(bug, seed):
    rng = random.Random(seed)
    seen, frontier, runs = {bug["src"]}, [(0, bug["src"], "")], 0
    for level in range(LH.LEVELS + 1):
        new = []
        for _, prog, _ in frontier:
            new += LH.expand(bug, prog, seen)
        runs += len(new)
        if any(c[0] == len(bug["cases"]) for c in new):
            return True, runs
        short = LH.shortlist(new)
        frontier = rng.sample(short, min(LH.BEAM, len(short)))
    return False, runs


def random_control():
    bs = json.loads((LH.HINTS / "bugs_hard.json").read_text())
    reach = json.loads((LH.HINTS / "reach.json").read_text()) if (LH.HINTS / "reach.json").exists() else {}
    key = lambda b: re.search(r"f_[0-9a-f]{6}", b["expr"]).group(0)
    per_seed = []
    for seed in range(5):
        res = {key(b): random_search(b, seed) for b in bs}
        per_seed.append((sum(v[0] for v in res.values()), sum(v[0] and reach.get(k, False) for k, v in res.items()),
                         sum(v[1] for v in res.values())))
        print(f"  random filter seed {seed}: {per_seed[-1][0]}/{len(bs)}", flush=True)
    blind = json.loads((LH.HINTS / "blind.json").read_text())
    fixed = [p[0] for p in per_seed]
    out = [f"The {len(bs)} hard bugs. The random filter is shown the same candidates as Haiku and picks {LH.BEAM} at "
           "random, at every level; 5 seeds.", "",
           "| filter | fixed | reachable fixed | test runs |", "|---|---|---|---|",
           f"| blind (the 3 passing most tests) | {sum(v[0] for v in blind.values())} | - | {sum(v[2] for v in blind.values()):,} |",
           f"| random (5 seeds) | {statistics.mean(fixed):.1f} (range {min(fixed)}-{max(fixed)}) | "
           f"{statistics.mean(p[1] for p in per_seed):.1f} | {statistics.mean(p[2] for p in per_seed):,.0f} |",
           "| Claude Haiku (from LOCAL_HINTS.md) | 17 | 16 | 2,316 |", "",
           f"If Haiku's 17 is above every random seed ({max(fixed)} at best), its picks carry information the test "
           "counts and chance do not."]
    section("Control: a random filter for neo4d's search", out)


# ------------------------------------------------------------------------------ coverage-guided search, file sizes

def _child_cov(conn, src, expr, cases):
    import copy as _copy
    import io as _io
    sys.stdout = _io.StringIO()
    out = []
    try:
        ns = {}
        exec(compile(src, "<candidate>", "exec"), ns)
        tree = ast.parse(expr, mode="eval").body
        left = compile(ast.Expression(tree.left), "<l>", "eval")
        approx = "approx" in expr
        for inp, exp in cases:
            hit = set()

            def tracer(frame, event, arg):
                if frame.f_code.co_filename == "<candidate>" and event == "line":
                    hit.add(frame.f_lineno - 1)
                return tracer
            ns["input_data"], ns["expected"] = _copy.deepcopy(inp), exp
            sys.settrace(tracer)
            try:
                got = eval(left, ns)
                ok = abs(got - exp) <= inp[-1] if approx else json.loads(json.dumps(got, default=list)) == exp
            except BaseException:                      # noqa: BLE001
                ok = False
            finally:
                sys.settrace(None)
            out.append((bool(ok), sorted(hit)))
    except BaseException:                              # noqa: BLE001
        out = [(False, [])] * len(cases)
    conn.send(out)


def coverage(src, expr, cases, timeout=10.0):
    a, b = LM.CTX.Pipe(duplex=False)
    p = LM.CTX.Process(target=_child_cov, args=(b, src, expr, cases))
    p.start()
    p.join(timeout)
    if p.is_alive():
        p.kill()
        p.join()
        return [(False, [])] * len(cases)
    return a.recv() if a.poll() else [(False, [])] * len(cases)


def ochiai(cov):
    """Suspicion of each line: executed by failing tests, rarely by passing ones."""
    fail = [set(l) for ok, l in cov if not ok]
    passed = [set(l) for ok, l in cov if ok]
    lines = set().union(*fail) if fail else set()
    score = {}
    for li in lines:
        ef = sum(li in f for f in fail)
        ep = sum(li in p for p in passed)
        score[li] = ef / math.sqrt(len(fail) * (ef + ep)) if ef else 0.0
    return score


def runs_to_fix(src, expr, cases, order, cap):
    lines = src.split("\n")
    runs = 0
    for li in order:
        for m in D.mutants(R.toks(lines[li])):
            new = LM.to_text(lines[li], list(m))
            if new == lines[li]:
                continue
            var = "\n".join(lines[:li] + [new] + lines[li + 1:])
            try:
                ast.parse(var)
            except SyntaxError:
                continue
            runs += 1
            if all(ok for ok, _ in LH.run_all(var, expr, cases)):
                return runs
            if runs >= cap:
                return None
    return None


def coverage_scaling(sizes=(1, 4, 16, 31), seeds=(0, 1, 2), cap=400):
    progs = LM.json_programs()
    pool = {}
    for name, expr in progs.items():
        src = (LM.QB / "correct_python_programs" / f"{name}.py").read_text()
        cases = [json.loads(l) for l in (LM.QB / "json_testcases" / f"{name}.json").read_text().splitlines() if l.strip()]
        good = [c for c in cases if LM.run(src, expr, [c], 1.5)[0]]
        if len(good) >= 2:
            pool[name] = (src.split('\n"""')[0].rstrip() + "\n", expr, good)
    names = sorted(pool)
    res = defaultdict(list)                            # (size, method) -> runs or None
    for seed in seeds:
        rng = random.Random(seed)
        for target in names:
            src0, expr, cases = pool[target]
            lines0 = src0.split("\n")
            muts = [(li, LM.to_text(lines0[li], list(m))) for li in LM.code_lines(src0) for m in D.mutants(R.toks(lines0[li]))]
            rng.shuffle(muts)
            bug = None
            for li, bad in muts:                       # a fault neo4d can undo, that the tests catch
                if bad == lines0[li]:
                    continue
                if lines0[li].strip() not in {LM.to_text(bad, list(m)).strip() for m in D.mutants(R.toks(bad))}:
                    continue
                prog = "\n".join(lines0[:li] + [bad] + lines0[li + 1:])
                try:
                    ast.parse(prog)
                except SyntaxError:
                    continue
                if not all(ok for ok, _ in LH.run_all(prog, expr, cases)):
                    bug = prog
                    break
            if bug is None:
                continue
            for size in sizes:
                others = rng.sample([n for n in names if n != target], size - 1)
                pos = rng.randrange(size)
                parts = [pool[n][0] for n in others]
                parts.insert(pos, bug)
                big = "\n\n".join(parts)
                code = LM.code_lines(big)
                cov = coverage(big, expr, cases)
                executed = sorted(set().union(*[set(l) for ok, l in cov if not ok]))
                susp = ochiai(cov)
                for method, order in (("every line, file order", code),
                                      ("lines the failing tests run", [li for li in code if li in set(executed)]),
                                      ("those lines, by suspicion (Ochiai)",
                                       sorted((li for li in code if li in susp), key=lambda li: (-susp[li], li)))):
                    res[(size, method)].append(runs_to_fix(big, expr, cases, order, cap))
            print(f"  coverage seed {seed} {target} done", flush=True)
    out = [f"One fault (one neo4d can undo, caught by the tests) in a target function, placed among other functions in "
           f"one file of 1, 4, 16 or 31 functions; 3 seeds x up to {len(names)} targets. Test runs until a variant passes "
           f"every test (the median over bugs; a search that has not found it after {cap} runs counts as a failure).", "",
           "| functions in the file | search | found within the budget | test runs to the fix (median) | mean |",
           "|---|---|---|---|---|"]
    for size in sizes:
        for method in ("every line, file order", "lines the failing tests run", "those lines, by suspicion (Ochiai)"):
            r = res[(size, method)]
            found = [x for x in r if x is not None]
            out.append(f"| {size} | {method} | {len(found)}/{len(r)} | "
                       f"{statistics.median(found) if found else '-'} | {statistics.mean(found) if found else 0:.1f} |")
    section("Coverage-guided search: does it scale to large files?", out)


# ---------------------------------------------------------------- baselines at an equal budget, seeds and statistics

BUDGET = 10


def generate(model, prompt, temperature, seed, stats, predict=900):
    import urllib.error
    import urllib.request
    stats["calls"] += 1
    body = json.dumps({"model": model, "prompt": prompt, "stream": False,
                       "options": {"temperature": temperature, "seed": seed, "num_predict": predict,
                                   "num_ctx": 8192}}).encode()
    for wait in (2, 5, 10, None):
        try:
            req = urllib.request.Request(LM.OLLAMA, data=body, headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(req, timeout=600) as r:
                return json.loads(r.read())["response"]
        except (urllib.error.URLError, TimeoutError, ConnectionError):
            if wait is None:
                return ""
            time.sleep(wait)


def code_of(reply):
    m = re.findall(r"```(?:python)?\n(.*?)```", reply or "", re.S)
    return max(m, key=len) if m else None


def passes(bug, prog):
    if not prog:
        return False, None
    try:
        ast.parse(prog)
    except SyntaxError:
        return False, None
    base = LH.run_all(prog, bug["expr"], bug["cases"])
    return all(ok for ok, _ in base), base


def bug_prompt(bug, extra=""):
    numbered = "\n".join(f"{n + 1:3d}  {l}" for n, l in enumerate(bug["src"].split("\n")))
    return (f"This Python program has a bug. {LH.first_failure(bug)}\n\n```\n{numbered}\n```\n\n{extra}"
            "Reply with the complete corrected program (without line numbers) in one ```python code block.")


def sample_filter(model, bug, seed, stats):
    for k in range(BUDGET):
        prog = code_of(generate(model, bug_prompt(bug), 0.0 if k == 0 else 0.8, seed * 1000 + k, stats))
        if passes(bug, prog)[0]:
            return True
    return False


def self_debug(model, bug, seed, stats):
    last = ""
    for k in range(BUDGET):
        prog = code_of(generate(model, bug_prompt(bug, last), 0.0 if k == 0 else 0.8, seed * 1000 + k, stats))
        ok, base = passes(bug, prog)
        if ok:
            return True
        if prog:
            last = f"Your previous attempt:\n```python\n{prog}\n```\n{LH.tests_feedback(bug, base)}\n\n"
    return False


def reflexion(model, bug, seed, stats):
    notes, last = [], ""
    while stats["calls"] < stats["start"] + BUDGET:
        k = stats["calls"] - stats["start"]
        extra = (("Notes from your earlier attempts:\n" + "\n".join(f"- {n}" for n in notes) + "\n\n") if notes else "") + last
        prog = code_of(generate(model, bug_prompt(bug, extra), 0.0 if k == 0 else 0.8, seed * 1000 + k, stats))
        ok, base = passes(bug, prog)
        if ok:
            return True
        if stats["calls"] >= stats["start"] + BUDGET or not prog:
            continue
        fb = LH.tests_feedback(bug, base)
        last = f"Your previous attempt:\n```python\n{prog}\n```\n{fb}\n\n"
        note = generate(model, f"{bug_prompt(bug)}\n\nAn attempt:\n```python\n{prog}\n```\n{fb}\n\nIn two or three "
                        "sentences, say what is wrong with this attempt and what to change. Do not write code.",
                        0.0, seed * 1000 + 500 + k, stats, predict=160)
        notes.append(" ".join((note or "").split())[:400])
    return False


def neo4d_loop(model, bug, seed, stats):
    last = None
    for k in range(BUDGET):
        reply = generate(model, bug_prompt(bug, f"Your previous attempt:\n```python\n{last[0]}\n```\n{last[1]}\n\n" if last else ""),
                         0.0 if k == 0 else 0.8, seed * 1000 + k, stats)
        prog = code_of(reply)
        if not prog:
            continue
        var, base, tried = LH.explore(bug, prog)
        if base is not None and all(ok for ok, _ in base):
            return True
        if var:
            return True
        last = (prog, LH.report_back(bug, base, tried))
    return False


METHODS = (("sample-and-filter", sample_filter), ("self-debugging", self_debug), ("Reflexion", reflexion),
           ("**neo4d loop**", neo4d_loop))


def bootstrap(per_bug, n=10000, seed=0):
    rng = random.Random(seed)
    k = len(per_bug)
    means = sorted(statistics.mean(per_bug[rng.randrange(k)] for _ in range(k)) for _ in range(n))
    return means[int(0.025 * n)], means[int(0.975 * n)]


def permutation_p(diffs, n=100000, seed=0):
    """Two-sided paired sign-flip test of the mean difference."""
    rng = random.Random(seed)
    obs = abs(statistics.mean(diffs))
    if obs == 0:
        return 1.0
    hits = sum(abs(statistics.mean(d if rng.random() < 0.5 else -d for d in diffs)) >= obs - 1e-12 for _ in range(n))
    return (hits + 1) / (n + 1)


def baselines(models, seeds=(0, 1, 2)):
    bs = json.loads((LH.HINTS / "bugs.json").read_text())
    store = REPO / ".build" / "baselines.json"
    done = json.loads(store.read_text()) if store.exists() else {}
    for model in models:
        for seed in seeds:
            for label, fn in METHODS:
                key = f"{model}|{seed}|{label}"
                if key in done:
                    continue
                row = {}
                calls = 0
                for b in bs:
                    stats = defaultdict(int)
                    stats["start"] = 0
                    row[b["name"]] = bool(fn(model, b, seed, stats))
                    calls += stats["calls"]
                done[key] = dict(fixed=row, calls=calls)
                store.write_text(json.dumps(done))
                print(f"  {model} seed {seed} {label}: {sum(row.values())}/{len(bs)} ({calls} calls)", flush=True)
    out = [f"The {len(bs)} real QuixBugs bugs. Every method may use at most {BUDGET} model calls a bug; seeds change the "
           "sampled attempts (the first attempt is greedy). Fixed: every test passes. Intervals: 95% bootstrap over bugs "
           "of the per-bug success rate averaged over seeds. p: a paired sign-flip permutation test, neo4d against the "
           "method, on per-bug success rates.", ""]
    for model in models:
        out += [f"### {model}", "", "| method | fixed per seed | mean | 95% interval (share of bugs) | calls per bug | "
                "neo4d minus method | p |", "|---|---|---|---|---|---|---|"]
        rate = {}
        for label, _ in METHODS:
            runs = [done[f"{model}|{s}|{label}"] for s in seeds if f"{model}|{s}|{label}" in done]
            if not runs:
                continue
            rate[label] = [statistics.mean(r["fixed"][b["name"]] for r in runs) for b in bs]
            lo, hi = bootstrap(rate[label])
            per_seed = [sum(r["fixed"].values()) for r in runs]
            calls = statistics.mean(r["calls"] for r in runs) / len(bs)
            cell = ""
            if label != "**neo4d loop**" and "**neo4d loop**" in rate:
                pass
            out.append([label, f"{', '.join(map(str, per_seed))}", f"{statistics.mean(per_seed):.1f}",
                        f"{lo:.0%}-{hi:.0%}", f"{calls:.1f}"])
        neo = rate.get("**neo4d loop**")
        rows = []
        for item in out:
            if isinstance(item, list):
                label = item[0]
                if neo is not None and label != "**neo4d loop**" and label in rate:
                    d = [a - b for a, b in zip(neo, rate[label])]
                    item += [f"{statistics.mean(d) * len(bs):+.1f} bugs", f"{permutation_p(d):.3f}"]
                else:
                    item += ["", ""]
                rows.append("| " + " | ".join(item) + " |")
            else:
                rows.append(item)
        out = rows + [""]
    section("Baselines at an equal budget, with seeds and statistics", out)


def main() -> int:
    args = sys.argv[1:]
    t0 = time.time()
    if "--law" in args:
        law_ablation()
    if "--agent" in args:
        agent_ablation()
    if "--random" in args:
        random_control()
    if "--coverage" in args:
        coverage_scaling()
    if "--baselines" in args:
        baselines(args[args.index("--baselines") + 1].split(","))
    print(f"  done ({time.time() - t0:.0f}s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
