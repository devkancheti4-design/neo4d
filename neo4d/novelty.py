"""Does novelty die? The share of new tasks whose pattern was never seen before, as experience grows.

If most tasks become repeats, a system with memory and generalisation covers more and more of them. Measured here on
the three streams neo4d has learned from, with the pattern it learns - the relation of each small fix or mutant:

    novelty rate       in each tenth of the stream, the share of items whose pattern had not appeared before
    Good-Turing        the share of items whose pattern occurs exactly once: the estimated chance the NEXT item is new
    Heaps' law         distinct patterns ~ K * n^beta; beta < 1 means novelty dies, and the fit says how fast:
                       the novelty rate is the slope, beta * V(n) / n

    python -m neo4d.novelty   -> results/NOVELTY.md
"""
from __future__ import annotations

import math
import random
import statistics
import sys
from collections import Counter

from neo4d import REPO
from neo4d import relate_live as RL


def curve(seq):
    seen, novel, distinct = set(), [], []
    for p in seq:
        novel.append(p not in seen)
        seen.add(p)
        distinct.append(len(seen))
    return novel, distinct


def heaps(distinct):
    pts = [(math.log(n), math.log(v)) for n, v in ((i + 1, d) for i, d in enumerate(distinct)) if n >= 10]
    mx, my = statistics.mean(x for x, _ in pts), statistics.mean(y for _, y in pts)
    beta = sum((x - mx) * (y - my) for x, y in pts) / sum((x - mx) ** 2 for x, _ in pts)
    return beta, math.exp(my - beta * mx)


def until(beta, K, rate):
    """Items needed before the fitted novelty rate beta * K * n^(beta-1) falls to rate."""
    if beta >= 1:
        return None
    return (rate / (beta * K)) ** (1 / (beta - 1))


def analyse(name, seqs, note):
    novs, dists, gts = [], [], []
    for seq in seqs:
        nv, ds = curve(seq)
        novs.append(nv)
        dists.append(ds)
        c = Counter(seq)
        gts.append(sum(1 for p in seq if c[p] == 1) / len(seq))
    n = len(seqs[0])
    deciles = [statistics.mean(sum(nv[i * n // 10:(i + 1) * n // 10]) / max(1, (i + 1) * n // 10 - i * n // 10)
                               for nv in novs) for i in range(10)]
    fits = [heaps(ds) for ds in dists]
    beta, K = statistics.mean(f[0] for f in fits), statistics.mean(f[1] for f in fits)
    return dict(name=name, n=n, distinct=statistics.mean(ds[-1] for ds in dists), deciles=deciles,
                gt=statistics.mean(gts), beta=beta, K=K, note=note,
                proj={r: until(beta, K, r) for r in (0.10, 0.05, 0.01)})


def main() -> int:
    out_rows = []
    d = RL.prep()
    bug_seqs = []
    for s in RL.SEEDS:
        seq = [d["rows"][i]["rel"] for bug in RL.stream(d, s) for i in bug]
        bug_seqs.append(seq)
    out_rows.append(analyse("real bugs, 49 projects (small fixes)", bug_seqs,
                            f"{len(d['rows'])} small fixes; 54% of one-line fixes are bigger edits, novel to the "
                            "relation abstraction whatever the experience"))
    c = RL.prep_click()
    out_rows.append(analyse("click's history, commit order (small fixes)", [[r["rel"] for r in c["rows"]]],
                            f"{len(c['rows'])} small fixes in real time order"))
    from neo4d import domain_mutation as D
    dom = D.Domain()
    items = []
    for x in dom.lines:
        for m in x["refs"]:
            keys = {k[0]: k for k in x["own"] if m in x["own"][k]}
            items.append(keys.get("ctx") or keys.get("lit"))
    mut_seqs = []
    for s in RL.SEEDS[:3]:
        seq = items[:]
        random.Random(s).shuffle(seq)
        mut_seqs.append(seq)
    out_rows.append(analyse("the mutation domain (standard library)", mut_seqs,
                            f"{len(items):,} mutants, their anchored relations, lines in random order"))
    out = ["# Does novelty die?", "",
           "Generated by `neo4d/novelty.py`. The share of new items whose pattern - the relation neo4d learns - had "
           "never appeared before, as experience grows. If novelty dies, memory and generalisation cover more and "
           "more of the world; if not, every new item still needs something new.", "",
           "| stream | items | distinct patterns | novelty, first tenth -> last tenth | Good-Turing: next item new | Heaps beta |",
           "|---|---|---|---|---|---|"]
    for r in out_rows:
        out.append(f"| {r['name']} | {r['n']:,} | {r['distinct']:,.0f} | {r['deciles'][0]:.0%} -> **{r['deciles'][-1]:.0%}** | "
                   f"**{r['gt']:.1%}** | {r['beta']:.2f} |")
    out += ["", "## The novelty rate, tenth by tenth", "",
            "| stream | " + " | ".join(f"{i + 1}" for i in range(10)) + " |", "|---|" + "---|" * 10]
    for r in out_rows:
        out.append(f"| {r['name']} | " + " | ".join(f"{v:.0%}" for v in r["deciles"]) + " |")
    out += ["", "## Where Heaps' law says it goes", "",
            "Items of experience before the fitted novelty rate falls to 10%, 5%, 1% (an extrapolation of the fit, "
            "not a measurement):", "", "| stream | 10% | 5% | 1% |", "|---|---|---|---|"]
    fmt = lambda v: "-" if v is None else (f"{v:,.0f}" if v < 1e9 else f"{v:.1e}")
    for r in out_rows:
        out.append(f"| {r['name']} | {fmt(r['proj'][0.10])} | {fmt(r['proj'][0.05])} | {fmt(r['proj'][0.01])} |")
    out += ["", "Notes: " + "; ".join(f"{r['name']}: {r['note']}" for r in out_rows) + "."]
    (REPO / "results" / "NOVELTY.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
