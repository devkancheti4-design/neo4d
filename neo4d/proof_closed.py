"""Can neo4d replace a model in a closed domain? It learns a whole codebase's mutation domain, and on every line we ask
whether its output alone is exactly the domain's answer - every real mutant, nothing else. That is the bar a model
would have to meet to do the job, and the lines that meet it are lines no model is needed for.

    codebases   click (Python), the Python standard library, npm's own source (JavaScript)
    1           taught on half of a codebase's files, run on EVERY line of the other half
    2           taught the WHOLE codebase, run on the whole codebase - the ceiling of what it can represent
    per line    complete   its candidates are exactly the teacher's mutants (the model is not needed)
                incomplete nothing wrong, but some real mutants missing
                noisy      some candidate is not a real mutant
                (lines where neither the teacher nor neo4d has anything are counted apart: nothing to do)

    python -m neo4d.proof_closed   -> results/PROOF_CLOSED.md
"""
from __future__ import annotations

import random
import sys
from collections import Counter
from pathlib import Path

from neo4d import KERNELS, REPO
from neo4d import domain_hard as H
from neo4d import domain_mutation as D
from neo4d import relate_live as RL
from neo4d.proof_grows import show

NPM = Path("/opt/homebrew/lib/node_modules/npm/lib")


def judge_lines(dom, act, lines):
    idx = D.Index(act)
    c = Counter()
    real = gen_real = gen_all = 0
    junk = Counter()
    missed = Counter()
    for i in lines:
        x = dom.lines[i]
        cands = set()
        src = {}
        for k in idx.on(x):
            g = dom.gen(k, i)
            for m in g:
                src.setdefault(m, k)
            cands |= g
        refs = x["refs"]
        rs = set(refs)
        real += len(rs)
        gen_real += len(cands & rs)
        gen_all += len(cands)
        if not rs and not cands:
            c["nothing to do"] += 1
        elif cands == rs:
            c["complete"] += 1
        elif cands <= rs:
            c["incomplete"] += 1
        else:
            c["noisy"] += 1
        for m in cands - rs:
            k = src[m]
            junk[f"{' '.join(k[1][0])} -> {' '.join(k[1][1])}"] += 1
        for m in rs - cands:
            missed[refs[m]] += 1
    work = c["complete"] + c["incomplete"] + c["noisy"]
    return dict(c=c, work=work, rec=gen_real / max(1, real), prec=gen_real / max(1, gen_all), junk=junk,
                missed=missed, real=real)


def main() -> int:
    law = RL.load_law(str(KERNELS / "relate_v2.c"))
    click = H.python_lines(sorted((REPO / "bench" / "click" / "src" / "click").glob("*.py")), lambda p: p.stem, "click")
    npm = H.c_lines(sorted(NPM.rglob("*.js")), lambda p: str(p.relative_to(NPM)), "npm", "js")
    lib = [(f"py:{n}", l, s, "py") for n, l, s in D.corpus()]
    dom = D.Domain(raw=click + npm + lib)
    S = H.sets_of(dom)
    out = ["# Can it replace a model in a closed domain?", "",
           "Generated by `neo4d/proof_closed.py`. The closed domain: code mutation (the standard operators; the "
           "reference mutator is the teacher). For every line of a codebase we ask whether neo4d's output alone is "
           "exactly the teacher's answer - every real mutant and nothing else. **Complete** lines are lines no model "
           "is needed for; **incomplete** lines miss some mutants but contain nothing wrong; **noisy** lines contain a "
           "wrong mutant. RELATE v2 decides every pattern.", ""]
    summary = []
    for name, key in (("click (Python)", "click"), ("Python standard library", "py"), ("npm's own source (JavaScript)", "npm")):
        idx = S[key]
        files = sorted({dom.lines[i]["net"] for i in idx})
        random.Random(0).shuffle(files)
        half = set(files[:len(files) // 2])
        tr = [i for i in idx if dom.lines[i]["net"] in half]
        te = [i for i in idx if dom.lines[i]["net"] not in half]
        if len(tr) > 30000:
            tr = random.Random(0).sample(tr, 30000)
        if len(te) > 20000:
            te = random.Random(1).sample(te, 20000)
        variants = {}
        for label, kinds in (("one token of context (as before)", ("ctx",)), ("two tokens before", ("ctx2",)),
                             ("one before, one after", ("ctxlr",)), ("both wider forms", ("ctx2", "ctxlr"))):
            variants[label] = judge_lines(dom, D.teach(dom, tr, law, kinds, costly_t=D.JUNK), te)
        best = max(variants, key=lambda k: variants[k]["c"]["complete"] / max(1, variants[k]["work"]))
        KINDS = {"one token of context (as before)": ("ctx",), "two tokens before": ("ctx2",),
                 "one before, one after": ("ctxlr",), "both wider forms": ("ctx2", "ctxlr")}[best]
        a_half = D.teach(dom, tr, law, KINDS, costly_t=D.JUNK)
        r_half = variants[best]
        whole = idx if len(idx) <= 30000 else random.Random(2).sample(idx, 30000)
        a_whole = D.teach(dom, whole, law, KINDS, costly_t=D.JUNK)
        r_whole = judge_lines(dom, a_whole, whole)
        out += [f"## {name}", "",
                f"{len(idx):,} code lines in {len(files)} files. Taught {len(tr):,} lines from half the files; run on "
                f"{len(te):,} lines of the other half.", "",
                "How much context a pattern keeps (half taught, other half run):", "",
                "| patterns | lines with work | **complete - no model needed** | incomplete | noisy | mutants found | precision |",
                "|---|---|---|---|---|---|---|"]
        for label, r in variants.items():
            w = max(1, r["work"])
            out.append(f"| {label}{' (best)' if label == best else ''} | {r['work']:,} | **{r['c']['complete'] / w:.1%}** | "
                       f"{r['c']['incomplete'] / w:.1%} | {r['c']['noisy'] / w:.1%} | {r['rec']:.1%} | {r['prec']:.1%} |")
        out += ["", f"With the best form ({best}):", "",
                "| | lines with work | **complete - no model needed** | incomplete | noisy | mutants found | precision |",
                "|---|---|---|---|---|---|---|"]
        for label, r in (("half taught, other half run", r_half), ("whole codebase taught, whole run", r_whole)):
            w = max(1, r["work"])
            out.append(f"| {label} | {r['work']:,} | **{r['c']['complete'] / w:.1%}** | {r['c']['incomplete'] / w:.1%} | "
                       f"{r['c']['noisy'] / w:.1%} | {r['rec']:.1%} | {r['prec']:.1%} |")
        out += ["", "What keeps the rest from being complete (half taught):", "",
                "- missed mutants by operator: " + ", ".join(f"{o} {n:,}" for o, n in r_half["missed"].most_common(5)),
                "- most frequent wrong mutants come from: " + "; ".join(
                    f"`{p}` {n:,}" for p, n in r_half["junk"].most_common(4)), ""]
        summary.append((name, r_half, r_whole, variants["one token of context (as before)"], best))
        print(f"  {name} done", flush=True)
    out += ["## Summary", "",
            "| codebase | complete lines, one token of context | complete lines, best context, half taught | whole taught | mutants found | precision |",
            "|---|---|---|---|---|---|"]
    for name, rh, rw, r1, best in summary:
        out.append(f"| {name} | {r1['c']['complete'] / max(1, r1['work']):.1%} | "
                   f"**{rh['c']['complete'] / max(1, rh['work']):.1%}** ({best}) | "
                   f"{rw['c']['complete'] / max(1, rw['work']):.1%} | {rh['rec']:.1%} | {rh['prec']:.1%} |")
    (REPO / "results" / "PROOF_CLOSED.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
